// Срок «ждём следующую серию» (сессия 16a, решения 303, 306–308). Один владелец числа на весь экстеншен:
// тень в странице (`page/shadow/empty-source-watch.ts`) и переезд сеанса в фоне
// (`background/handoff/video-relocation.ts`) ждут одинаково, а плеер узнаёт это число из
// `awaiting_next_episode{patience_ms}`.

/**
 * Сколько ждём следующую серию после того, как текущая доиграла у нас до конца (часы плеера сказали
 * `ended`) и страница сняла источник или поставила новый файл. Решение владельца 308: 60 с сразу.
 * Почему так много: вкладку, скрытую больше пяти минут, Chromium будит раз в минуту, и сайт ставит
 * следующую серию только на таком «пробуждении» (находка 09a2 на YouTube). Посреди серии ждём
 * по-прежнему коротко (`EMPTY_SOURCE_GRACE_MS`, `NEXT_VIDEO_WAIT_MS`).
 */
export const NEXT_EPISODE_WAIT_MS = 60_000;
