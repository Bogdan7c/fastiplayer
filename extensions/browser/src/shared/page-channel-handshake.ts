// Рукопожатие участка 1 (MAIN-мир ⇄ изолированный мир) — договор пакетов A1 и B сессии 09a.
//
// Изолированный мир на document_start создаёт MessageChannel, оставляет себе port1 и передаёт port2
// MAIN-миру одним `window.postMessage(HANDSHAKE_MESSAGE, "*", [port2])`. MAIN-мир слушает `message`
// на window в фазе захвата (его слушатель зарегистрирован раньше любых скриптов страницы), принимает
// ТОЛЬКО первое такое сообщение с `event.source === window` и ровно одним портом и зовёт
// `stopImmediatePropagation()` — обработчики страницы его не видят и порт не получают.
// Дальше весь обмен идёт по личному порту: страница его не видит и не может подделать.
//
// Почему не обмен через window.postMessage: каждое наше сообщение (и каждый кусок байтов) получали бы
// все обработчики `message` страницы — лишняя работа на её потоке и риск сломать чужую логику.
//
// Встреча перед передачей порта (находка после 09b). Браузер гарантирует ПОРЯДОК двух наших
// document_start-скриптов, но не то, что они исполнятся в одном синхронном отрезке: Firefox ждёт
// компиляцию каждого скрипта отдельно (`await` в ExtensionContent), и между изолированным и MAIN-
// скриптом успевает выполниться задача доставки `message`. Слепой `postMessage` на старте тогда
// приходил РАНЬШЕ слушателя MAIN-мира: порт терялся (и доставался обработчикам страницы), MAIN-мир
// оставался без канала, а фон на «какие у тебя видео» слышал тишину → «no_video».
// Поэтому порт уходит только тогда, когда слушатель MAIN-мира ТОЧНО стоит, в любом порядке запуска:
//   - MAIN-мир на старте ставит слушатель `message`, затем шлёт синхронное событие READY;
//     изолированный мир, если уже стоит, отвечает на него рукопожатием;
//   - изолированный мир на старте шлёт отменяемое событие OFFER; если MAIN-мир уже стоит, он отменяет
//     его (`preventDefault`), и изолированный мир отправляет рукопожатие сразу; иначе ждёт READY.
// Порт отправляется не больше одного раза за жизнь документа; после встречи обе стороны снимают
// слушатели событий встречи. События без данных (`detail` нет): между мирами Firefox идёт только факт.

/** MAIN → изолированный: «мой слушатель `message` стоит — присылай порт». */
export const PAGE_CHANNEL_READY_EVENT = "fastiplayer-bridge:page-channel-ready";

/** Изолированный → MAIN (отменяемое): «у меня есть порт; отмени, если ты уже слушаешь». */
export const PAGE_CHANNEL_OFFER_EVENT = "fastiplayer-bridge:page-channel-offer";

/** Поле-метка рукопожатия. Значение — номер версии внутреннего договора. */
export const HANDSHAKE_MARKER_FIELD = "fastiplayerBridgePageChannel";

/** Версия внутреннего договора участка 1 (меняется вместе с handoff-contract.ts). */
export const HANDSHAKE_VERSION = 1;

/** Сообщение рукопожатия (порт передаётся отдельно, в списке transfer). */
export const HANDSHAKE_MESSAGE: Readonly<Record<string, number>> = Object.freeze({
  [HANDSHAKE_MARKER_FIELD]: HANDSHAKE_VERSION,
});
