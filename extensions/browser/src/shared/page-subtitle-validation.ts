// Пограничник событий субтитров страницы (сессия 13b2): строгая форма `subtitle_document` и
// `subtitle_track_source` по договору `page-subtitle-contract.ts`.
//
// Вызывается из `parsePageEvent` (изолированный мир и повторно фон). Страница может подделать
// любое сообщение MAIN-мира, поэтому пропускается только ровно договорная форма: известные поля,
// верные типы, длины и диапазоны. Приведение языка и подписи к правилам протокола — дело фона:
// здесь только «это строка разумной длины».

import { MAX_PAGE_SUBTITLE_DOCUMENT_BYTES } from "../protocol/limits.ts";
import {
  PAGE_SUBTITLE_DISPLAYS,
  SUBTITLE_FORMAT_HINTS,
} from "../protocol/session/page-subtitles.ts";
import {
  MAX_PAGE_SUBTITLE_LABEL_CHARS,
  MAX_PAGE_SUBTITLE_LANGUAGE_CHARS,
  PAGE_SUBTITLE_DOCUMENT_ORIGINS,
  type PageSubtitleEvent,
  type PageSubtitleNaming,
} from "./page-subtitle-contract.ts";
import {
  MAX_U32,
  hasExactKeys,
  isFileSourceUrl,
  isIntegerInRange,
  isOneOf,
  isPageBytes,
  isPlainRecord,
  referrerFactsOf,
  type PlainRecord,
} from "./page-value-checks.ts";

const NAMING_KEYS: readonly string[] = ["language", "label", "auto_generated"];
const DOCUMENT_KEYS: readonly string[] = ["kind", "key", "naming", "format_hint", "origin", "display", "bytes"];
const TRACK_SOURCE_KEYS: readonly string[] = ["kind", "key", "naming", "display", "url", "referrer_origin", "referrer_policy"];

/** Ключ дорожки документа: 1..2^32-1 (ноль — признак забытого поля). */
function isPageSubtitleKey(value: unknown): value is number {
  return isIntegerInRange(value, 1, MAX_U32);
}

/** Непустая строка не длиннее `maxChars` или `null`. */
function isOptionalText(value: unknown, maxChars: number): value is string | null {
  return value === null || (typeof value === "string" && value.length >= 1 && value.length <= maxChars);
}

function parseNaming(value: unknown): PageSubtitleNaming | undefined {
  if (!isPlainRecord(value) || !hasExactKeys(value, NAMING_KEYS)) return undefined;
  const language = value["language"];
  const label = value["label"];
  const autoGenerated = value["auto_generated"];
  const valid =
    isOptionalText(language, MAX_PAGE_SUBTITLE_LANGUAGE_CHARS) &&
    isOptionalText(label, MAX_PAGE_SUBTITLE_LABEL_CHARS) &&
    typeof autoGenerated === "boolean";
  // Новый объект: дальше уходит только проверенное, а не объект страницы с его прототипом.
  return valid ? { language, label, auto_generated: autoGenerated } : undefined;
}

function parseDocumentEvent(value: PlainRecord): PageSubtitleEvent | undefined {
  const key = value["key"];
  const naming = parseNaming(value["naming"]);
  const formatHint = value["format_hint"];
  const origin = value["origin"];
  const display = value["display"];
  const bytes = value["bytes"];
  const valid =
    hasExactKeys(value, DOCUMENT_KEYS) &&
    isPageSubtitleKey(key) &&
    naming !== undefined &&
    isOneOf(formatHint, SUBTITLE_FORMAT_HINTS) &&
    isOneOf(origin, PAGE_SUBTITLE_DOCUMENT_ORIGINS) &&
    isOneOf(display, PAGE_SUBTITLE_DISPLAYS) &&
    isPageBytes(bytes, MAX_PAGE_SUBTITLE_DOCUMENT_BYTES);
  // Байты не копируются: тот же вид идёт дальше (точную копию с transfer делает ретранслятор).
  return valid ? { kind: "subtitle_document", key, naming, format_hint: formatHint, origin, display, bytes } : undefined;
}

function parseTrackSourceEvent(value: PlainRecord): PageSubtitleEvent | undefined {
  const key = value["key"];
  const naming = parseNaming(value["naming"]);
  const display = value["display"];
  const url = value["url"];
  const referrer = referrerFactsOf(value["referrer_origin"], value["referrer_policy"]);
  const valid =
    hasExactKeys(value, TRACK_SOURCE_KEYS) &&
    isPageSubtitleKey(key) &&
    naming !== undefined &&
    isOneOf(display, PAGE_SUBTITLE_DISPLAYS) &&
    isFileSourceUrl(url) &&
    referrer !== undefined;
  return valid
    ? { kind: "subtitle_track_source", key, naming, display, url, referrer_origin: referrer.origin, referrer_policy: referrer.policy }
    : undefined;
}

/**
 * Разбор события субтитров страницы; `undefined` — не событие субтитров или мусор. Вызывающий
 * (`parsePageEvent`) передаёт сюда только записи с `kind` субтитров.
 */
export function parsePageSubtitleEvent(value: PlainRecord): PageSubtitleEvent | undefined {
  switch (value["kind"]) {
    case "subtitle_document":
      return parseDocumentEvent(value);
    case "subtitle_track_source":
      return parseTrackSourceEvent(value);
    default:
      return undefined;
  }
}
