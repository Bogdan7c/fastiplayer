// Короткий отпечаток подписи пункта меню сайта (общий помощник адаптеров вариантов).
//
// Зачем: id пункта, который уходит плееру, часто строится из НОМЕРА пункта на странице. Между описанием меню
// и выбором зрителя сайт мог пересобрать список (смена ролика, серии, реклама), и тот же номер указал бы
// на соседа. Отпечаток подписи в id позволяет адаптеру заметить подмену и честно ответить «такого нет»,
// а не нажать чужой пункт.

/**
 * Отпечаток строки: FNV-1a, 32 бита, в base36 (не длиннее 7 знаков, только `0-9 a-z` — годится в id
 * протокола). Это не защита от подделки, а дешёвая проверка «на этом месте та же подпись».
 */
export function optionFingerprintOf(text: string): string {
  // Начальное значение и множитель — стандартные константы FNV-1a для 32 бит.
  let hash = 0x811c9dc5;
  for (let index = 0; index < text.length; index += 1) {
    // `Math.imul` + `>>> 0` — умножение по модулю 2^32 без потери точности чисел JavaScript.
    hash = Math.imul(hash ^ text.charCodeAt(index), 0x01000193) >>> 0;
  }
  return hash.toString(36);
}
