// Паспорт адаптера сайта: кто он и какой версии (сессия 14b, решение 283).
//
// Версия поднимается при каждой правке поведения адаптера (новые селекторы, другой путь нажатия).
// Она нужна только журналу разработчика: по ней видно, какой адаптер работал на странице, когда
// что-то пошло не так. Адресов и названий страницы в паспорте нет и быть не может.

/** Паспорт адаптера одного сайта или семейства плееров. */
export interface SiteAdapterIdentity {
  /** Короткое имя без пробелов: `youtube`, `ima`, `playerjs`. Пишется в журнал разработчика. */
  readonly id: string;
  /** Версия поведения адаптера, целое ≥ 1. */
  readonly version: number;
}

/** Строка паспорта для журнала разработчика: `youtube@1`. */
export function describeSiteAdapter(identity: SiteAdapterIdentity): string {
  return `${identity.id}@${identity.version}`;
}
