// Тайминги связи с посредником. Каждая константа — с обоснованием, «магических» чисел в коде нет.

// Окно, в течение которого порт, закрывшийся БЕЗ единого ответа, считаем «посредник не запустился»
// (нет манифеста native messaging, чужой ID, нет прав). Браузер сообщает об этом за миллисекунды,
// а настоящий посредник без ответа не закрывается: плеер он ждёт до 5 с (results/05.md) и всё равно
// отвечает `refused`. 1 с — с большим запасом над задержкой запуска процесса.
export const HOST_STARTUP_WINDOW_MS = 1_000;

// Сколько ждём ответ на `hello`. Посредник ждёт дверь плеера до 5 с (запуск плеера с нуля)
// и сам отвечает `refused{player_not_responding}` при тишине; 8 с = 5 с + запас на запуск посредника.
export const HELLO_REPLY_TIMEOUT_MS = 8_000;

// Сколько ждём ответ на `open_session`: плеер может ещё и открывать окно. Больше, чем у `hello`,
// но не бесконечно, чтобы вызывающий код (сессия 10) не висел.
export const OPEN_SESSION_REPLY_TIMEOUT_MS = 12_000;

// Паузы между повторами при потере связи: 0,5 → 1 → 2 → 4 → 8 → 16 → 30 → 30 … с.
// Быстро ловим короткий перезапуск плеера, потом удваиваем, чтобы не будить систему зря;
// потолок 30 с — чтобы вернувшийся плеер замечали не дольше, чем через полминуты.
export const RETRY_DELAYS_MS: readonly number[] = [500, 1_000, 2_000, 4_000, 8_000, 16_000, 30_000];

// Через сколько без нужды и без запросов закрываем порт. Открытый порт держит процесс посредника
// и service worker, поэтому вечно держать нельзя; 30 с — чтобы повторное открытие попапа
// не пересоздавало процесс.
export const PORT_IDLE_CLOSE_MS = 30_000;
