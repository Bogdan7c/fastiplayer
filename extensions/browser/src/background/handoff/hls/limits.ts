// Числа HLS-передачи (сессия 10a2). Все пороги живут здесь, с объяснением, откуда взяты.

/**
 * Сколько записей держит стойка номерков. Живой поток обновляет плейлист каждые несколько секунд
 * и каждый раз приносит новые сегменты: за часы таблица росла бы без предела. 16 384 записей - это
 * больше суток живого потока с сегментами по 6 с и запас на ABR-перекладки; старейшие записи
 * вытесняются (поздний запрос получит `refused`, плеер перечитает плейлист и получит свежие номерки).
 */
export const MAX_HANDLE_DESK_ENTRIES = 16_384;

/**
 * Номерок «отказ»: его стойка НЕ выдаёт никогда. Им пишется каждый адрес, который нельзя выдать
 * (чужая схема, локальный адрес, адрес-заглушка от страницы): плеер просит такой номерок и сразу
 * получает `refused`. Равен наибольшему u32, поэтому счётчик останавливается перед ним.
 */
export const REFUSED_RESOURCE_HANDLE = 0xffff_ffff;

/** Первый номерок сеанса: корневой плейлист. */
export const FIRST_RESOURCE_HANDLE = 0;

/** Метка начала плейлиста HLS (RFC 8216, 4.3.1.1). */
export const PLAYLIST_SIGNATURE = "#EXTM3U";

/** Длина метки плейлиста в байтах (она ASCII). */
export const PLAYLIST_SIGNATURE_BYTES = PLAYLIST_SIGNATURE.length;

/** Длина UTF-8 BOM: перед меткой он допустим. */
export const UTF8_BOM_BYTES = 3;

/**
 * Сколько ведущих пробельных ASCII-байт (пробел, табуляция, переводы строк) допускается перед
 * меткой плейлиста. Сервер вправе начать файл с пустой строки; больше - уже не плейлист.
 */
export const MAX_PLAYLIST_LEADING_WHITESPACE_BYTES = 16;

/**
 * Сколько первых байт тела нужно, чтобы решить «плейлист или нет»: BOM + пробелы + метка. Пока
 * байт меньше, тело придерживается (это ≤ 26 байт, на задержку не влияет); короткое тело
 * решается по концу потока.
 */
export const PLAYLIST_SNIFF_BYTES = UTF8_BOM_BYTES + MAX_PLAYLIST_LEADING_WHITESPACE_BYTES + PLAYLIST_SIGNATURE_BYTES;
