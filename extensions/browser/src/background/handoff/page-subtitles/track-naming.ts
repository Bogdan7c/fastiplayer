// Имя дорожки субтитров страницы по правилам протокола 1.5 (сессия 13b2, решения 270, 276).
//
// Страница называет дорожку как попало: `srclang` бывает мусором, `label` - слишком длинным или с
// символами переворота текста. Плеер такие строки отвергает целиком (сторож закрыл бы сеанс 4003),
// поэтому фон приводит имя к правилам протокола ДО отправки:
// - язык - только тег, прошедший ту же проверку, что у плеера; иначе «язык не назван»;
// - подпись - без управляющих символов и переворота текста, не длиннее 256 байт UTF-8
//   (обрезка по границе символа); пустая - «подписи нет»;
// - автосубтитры без подписи страницы (адаптер timedtext YouTube) получают подпись
//   «<язык по-английски> (auto-generated)», чтобы ручные и авто не слились в два «English».
// Функции чистые: ни сети, ни состояния.

import type { PageSubtitleNaming } from "../../../shared/page-subtitle-contract.ts";
import { captionLabelOf } from "../../../adapters/capabilities/subtitle-naming/caption-label.ts";
import { MAX_SUBTITLE_LABEL_BYTES } from "../../../protocol/limits.ts";
import { ProtocolFailure } from "../../../protocol/errors.ts";
import type { PageSubtitleLabel, PageSubtitleLanguage } from "../../../protocol/session/page-subtitles.ts";
import { checkSubtitleLanguageTag, isAllowedDisplayCodePoint } from "../../../protocol/text.ts";

/** Имя дорожки в виде полей заголовка `subtitle_track_offered`. */
export interface ProtocolTrackNaming {
  readonly language: PageSubtitleLanguage;
  readonly label: PageSubtitleLabel;
}

/** Разрывы строки и табуляция: в подписи они разделяют слова. */
function isLineBreakOrTab(codePoint: number): boolean {
  return (codePoint >= 0x09 && codePoint <= 0x0d) || codePoint === 0x85 || codePoint === 0x2028 || codePoint === 0x2029;
}

/** Сколько байт займёт кодовая точка в UTF-8. */
function utf8BytesOf(codePoint: number): number {
  if (codePoint < 0x80) return 1;
  if (codePoint < 0x800) return 2;
  return codePoint < 0x10000 ? 3 : 4;
}

/**
 * Привести подпись к виду протокола: разрывы строк - пробелы (подряд идущие сжимаются), запрещённые
 * символы и одиночные суррогаты убраны, края обрезаны, длина не больше `MAX_SUBTITLE_LABEL_BYTES`
 * байт UTF-8 по границе символа. Пустой итог означает «подписи нет».
 */
export function sanitizeSubtitleLabel(rawLabel: string): string {
  let cleaned = "";
  let byteLength = 0;
  for (const rawCharacter of rawLabel) {
    const rawCodePoint = rawCharacter.codePointAt(0) ?? 0;
    const character = isLineBreakOrTab(rawCodePoint) ? " " : rawCharacter;
    const codePoint = character.codePointAt(0) ?? 0;
    const isLoneSurrogate = codePoint >= 0xd800 && codePoint <= 0xdfff;
    if (isLoneSurrogate || !isAllowedDisplayCodePoint(codePoint)) continue;
    // Пробелы в начале и подряд не копим: подпись из одних пробелов станет пустой.
    if (character === " " && (cleaned === "" || cleaned.endsWith(" "))) continue;
    const characterBytes = utf8BytesOf(codePoint);
    if (byteLength + characterBytes > MAX_SUBTITLE_LABEL_BYTES) break;
    cleaned += character;
    byteLength += characterBytes;
  }
  return cleaned.trimEnd();
}

/** Язык по правилу тега протокола: годный тег - `known`, всё прочее (в том числе `null`) - `unknown`. */
export function protocolLanguageOf(rawLanguage: string | null): PageSubtitleLanguage {
  if (rawLanguage === null) return { kind: "unknown" };
  try {
    checkSubtitleLanguageTag(rawLanguage);
  } catch (error) {
    // Нарушение правила тега - обычное дело для страницы; любая другая ошибка - наш баг, глушить нельзя.
    if (error instanceof ProtocolFailure) return { kind: "unknown" };
    throw error;
  }
  return { kind: "known", tag: rawLanguage };
}

/**
 * Подпись автосубтитров: «English (auto-generated)»; без названия языка - «Auto-generated». Саму подпись строит
 * общая функция `captionLabelOf` - ею же подписаны пункты меню субтитров страницы (15a2).
 */
function autoGeneratedLabel(language: PageSubtitleLanguage): string {
  const tag = language.kind === "unknown" ? null : language.tag;
  return sanitizeSubtitleLabel(captionLabelOf({ language: tag, autoGenerated: true, autoTranslated: false }));
}

/** Имя дорожки в полях протокола: язык по тегу, подпись очищена, у автосубтитров без подписи - сочинена. */
export function protocolNamingOf(naming: PageSubtitleNaming): ProtocolTrackNaming {
  const language = protocolLanguageOf(naming.language);
  const cleanedLabel = naming.label === null ? "" : sanitizeSubtitleLabel(naming.label);
  if (cleanedLabel !== "") return { language, label: { kind: "text", text: cleanedLabel } };
  if (naming.auto_generated) return { language, label: { kind: "text", text: autoGeneratedLabel(language) } };
  return { language, label: { kind: "none" } };
}
