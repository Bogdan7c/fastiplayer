// Тайминги и пределы передачи вкладки (сессия 09a). Каждая константа — с обоснованием.

import { MAX_FORWARDED_APPEND_BYTES, MAX_PAGE_BYTES_EVENT_BYTES } from "../../shared/page-message-validation.ts";

/**
 * Сколько ждём `attached` после отправки `attach`. Плеер сам закрывает сеанс 4007, если `attach`
 * не пришёл за 5 с после рукопожатия WebSocket (browser-bridge-session); ответ на исправный `attach`
 * идёт за миллисекунды. 10 с — запас на занятый плеер (открывает окно), но не бесконечно.
 */
export const ATTACH_REPLY_TIMEOUT_MS = 10_000;

/**
 * Сколько ждём `handoff_began` от MAIN-мира. Он отвечает сразу из обработчика порта, задержка —
 * только занятость потока страницы и путь через изолированный мир; 5 с — с большим запасом.
 */
export const HANDOFF_BEGIN_REPLY_TIMEOUT_MS = 5_000;

/**
 * Сколько ждём `handoff_ended{returned}` после нашего `end_handoff`, прежде чем закрыть сеанс сами.
 * Снятие тени синхронное; таймаут нужен только против зависшей/ушедшей страницы.
 */
export const HANDOFF_END_REPLY_TIMEOUT_MS = 5_000;

/**
 * Порог `bufferedAmount` сокета, выше которого новые рамки не отдаём в сокет, а держим в своей
 * очереди. Иначе всплеск (повтор запомненного до 64 МиБ, решение 176) целиком лёг бы в буфер
 * браузера, и «полон» от плеера уже ничего бы не придержал. 8 МиБ — несколько секунд потока даже
 * на всплеске перемотки (до 5 МиБ/с, results/00c.md).
 */
export const SOCKET_HIGH_WATER_BYTES = 8 * 1024 * 1024;

/**
 * Как часто проверяем, освободился ли буфер сокета: у WebSocket нет события «буфер ушёл».
 * 20 мс — на loopback буфер уходит быстро; реже — лишняя задержка, чаще — лишние пробуждения.
 */
export const SOCKET_DRAIN_POLL_MS = 20;

/**
 * Потолок своей очереди сеанса (сообщения + рамки, ещё не отданные сокету), байт.
 * Должен вместить повтор запомненного при старте (до ~64 МиБ, решение 176) плюс живой поток,
 * пока плеер говорит «полон». Переполнение значит, что страница не слушает «полон»: сеанс честно
 * закрывается, тень снимается (молча выбрасывать куски нельзя — у плеера была бы дыра в потоке).
 */
export const MAX_SESSION_QUEUE_BYTES = 128 * 1024 * 1024;

// Очередь обязана вмещать хотя бы одно самое крупное событие страницы.
if (MAX_SESSION_QUEUE_BYTES < MAX_PAGE_BYTES_EVENT_BYTES) {
  throw new Error("MAX_SESSION_QUEUE_BYTES must hold at least one page bytes event");
}
// Кусок, который MAIN-мир согласен копировать, обязан помещаться в очередь: иначе копия бесполезна.
if (MAX_SESSION_QUEUE_BYTES < MAX_FORWARDED_APPEND_BYTES) {
  throw new Error("MAX_SESSION_QUEUE_BYTES must hold the largest forwarded append");
}
