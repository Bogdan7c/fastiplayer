// Адрес вкладки сеанса с начала текущего видео (сессия 16a, решение 42): одностраничник сменил адрес без
// смены документа (`pushState`, `replaceState`, хеш), источник снят, нового нет — это уход со страницы
// («Source tab closed», досмотр скачанного), а не «страница забрала видео» (4009).
//
// Владеет двумя адресами: последним, что сообщил браузер о главном документе вкладки, и «опорным» —
// тем, что был, когда на экране плеера началось текущее видео (тень встала или страница начала новое
// поколение). Решение «сменился ли» принимает только этот модуль; адрес наружу не отдаётся.
//
// Известные пределы:
// - сравнивается адрес целиком: сайт, который пишет в адрес секунду ролика (`replaceState` с `?t=`),
//   превратит честное 4009 в уход страницы. Оба конца закрывают окно, разница — только надпись;
// - сайт, сменивший поколение РАНЬШЕ своего `pushState`, оставит опорным адрес прошлой серии: уход с новой
//   серии тогда тоже «уход» (верно), а её честный конец посреди — тоже «уход» (неточно, но не опасно).

/** Сменился ли адрес вкладки с начала текущего видео. */
export type PageAddressSinceVideoBegan = "unchanged" | "changed";

export interface PageAddressTracker {
  /** Браузер сообщил адрес главного документа вкладки сеанса (тот же адрес повторно — не смена). */
  addressSeen(url: string): void;
  /** На экране плеера началось новое видео или поколение: текущий адрес становится опорным. */
  videoBegan(): void;
  /**
   * Сменился ли адрес с начала текущего видео. Опорного адреса нет (браузер не назвал адрес при старте и
   * не сообщал его с тех пор) — судить не о чем, ответ «не сменился»: прежнее поведение (4009).
   */
  sinceVideoBegan(): PageAddressSinceVideoBegan;
}

/** `openedUrl` — адрес вкладки при старте сеанса (`HandoffTarget.tabUrl`), он же первый опорный. */
export function createPageAddressTracker(openedUrl: string | undefined): PageAddressTracker {
  let latestUrl = openedUrl;
  let videoStartUrl = openedUrl;
  return {
    addressSeen(url) {
      latestUrl = url;
    },
    videoBegan() {
      videoStartUrl = latestUrl;
    },
    sinceVideoBegan() {
      if (videoStartUrl === undefined || latestUrl === undefined) return "unchanged";
      return latestUrl === videoStartUrl ? "unchanged" : "changed";
    },
  };
}
