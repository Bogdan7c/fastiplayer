// Что известно о просмотре видео одного MediaSource (решение 364) — общий язык потолка памяти и того,
// кто видит элементы страницы.
//
// Потолок памяти («память без копий») отдаёт сначала уже просмотренное. Сам он про элементы и позицию
// страницы ничего не знает и знать не должен: он спрашивает владельца MediaSource (`JournalOwnerProbe`
// в memory-budget.ts), а тот отвечает одним из состояний ниже. Откуда берётся ответ в главном потоке —
// media-source-viewing.ts; воркер элементов не видит и всегда отвечает «неизвестно».

/** Где на странице стоит видео, которое ещё ни разу не играло. */
export type NotStartedPlace =
  /** Элемент известен, но в документе его сейчас нет: показать его зрителю страница не может. */
  | { readonly kind: "off_page" }
  /**
   * Элемент в документе. `distanceFromView` — насколько он далёк от окна (пиксели от центра окна до
   * центра элемента): чем дальше, тем позже до него долистают. Читается лениво — мерить раскладку
   * страницы стоит, только когда до этих видео дошла очередь отдавать память.
   */
  | { readonly kind: "on_page"; readonly distanceFromView: () => number };

/** Что владелец MediaSource знает о его просмотре прямо сейчас. */
export type JournalViewing =
  /** Ничего не известно (воркер, элемент не найден, сбой чтения страницы). Не считается ни просмотренным, ни начатым. */
  | { readonly kind: "unknown" }
  /** Видео уже смотрели, и зритель с него ушёл: пройденный ролик ленты. */
  | { readonly kind: "passed" }
  /**
   * Видео идёт на странице: играет или стоит на паузе на экране. `playheadSeconds` — позиция страницы.
   * `playback` — играет ли оно сейчас: у играющего потеря вокруг текущей секунды проходит сама (страница
   * уходит дальше, и под её позицией снова лежат данные), у стоящего — остаётся до возврата зрителя.
   */
  | { readonly kind: "watching_on_page"; readonly playheadSeconds: number; readonly playback: "playing" | "paused" }
  /**
   * Видео идёт в окне плеера, и повтор журнала плеер уже получил: всё скачанное у него есть, дальше он
   * берёт живой поток. Журнал понадобится, только если зритель вернёт видео странице и отдаст снова.
   */
  | { readonly kind: "in_player" }
  /** Видео ещё ни разу не играло: его начало — самое ценное, что о нём помнит журнал. */
  | { readonly kind: "not_started"; readonly place: NotStartedPlace };

/** Ответ владельца, который о просмотре не знает ничего. */
export const VIEWING_UNKNOWN: JournalViewing = { kind: "unknown" };
