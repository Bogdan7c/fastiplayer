// Сторож «переданный ролик ушёл с экрана, и страница его остановила» (16b2, решения 354, 359).
//
// Так листает лента коротких видео: Instagram ставит ушедший ролик на паузу, когда тот уже за краем окна;
// TikTok вынимает его из документа и ставит на паузу. Оба признака вместе — повод фону открыть переезд на
// ролик, который страница запустит следующим. Порознь — нет:
// - ушёл с экрана, но играет — человек листает к комментариям обычной страницы, а видео идёт; превью по
//   наведению не должно увести окно (решение 359);
// - на паузе, но на экране — человек или страница просто поставили паузу.
//
// Сторож — чистое правило без DOM: факты (видимая площадь, пауза страницы) ему подаёт контроллер тени в
// моменты, когда они могут смениться: страница позвала `pause()` и пришёл тик часов плеера. Донесение одно
// на уход; следующее — только после того, как ролик вернулся на экран или страница его снова запустила.

/** Что сделать после проверки. */
export type ScreenExitStep = "report_left_screen" | "nothing";

export class ScreenExitWatch {
  /** Об этом уходе уже донесено. */
  #reported = false;

  /** Страница видит ролик играющим: следующий уход с экрана — новое донесение. */
  notePlaying(): void {
    this.#reported = false;
  }

  /**
   * Страница видит ролик на паузе (её `pause()`, конец ролика или медиаклавиша зрителя, которую она
   * исполнила). `visibleAreaPx` — его видимая площадь сейчас: 0 — вне окна, вне документа или скрыт стилями.
   */
  notePaused(visibleAreaPx: number): ScreenExitStep {
    if (visibleAreaPx > 0) {
      // Ролик снова на экране: следующий уход — новое донесение.
      this.#reported = false;
      return "nothing";
    }
    if (this.#reported) return "nothing";
    this.#reported = true;
    return "report_left_screen";
  }
}
