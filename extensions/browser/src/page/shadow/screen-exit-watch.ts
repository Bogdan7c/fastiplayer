// Сторож «переданный ролик уходит с экрана, и страница его остановила» (16b2, решения 354, 359).
//
// Так листает лента коротких видео. Оба признака вместе — повод фону открыть переезд на ролик, который
// страница запустит следующим. Порознь — нет:
// - уходит с экрана, но играет — человек листает к комментариям обычной страницы, а видео идёт; превью по
//   наведению не должно увести окно (решение 359);
// - на паузе, но на экране — человек или страница просто поставили паузу.
//
// Две точки проверки, и у каждой своё «ушёл с экрана»:
//
// 1. Страница позвала `pause()` — ролик считается уходящим, если на экране меньше `REEL_ON_SCREEN_SHARE` его
//    площади. Живой Instagram (прогон 18 ноября 2026 без входа, с мостом и наблюдателем в главном мире;
//    находка живой проверки, решение 361):
//    - страница переключает ролик на полпути прокрутки: `play()` нового и `pause()` прежнего идут одной
//      задачей или с разницей в десятки миллисекунд, и прежний в этот миг ещё виден на 12–53 % площади;
//    - ролик ниже окна, поэтому после прилипания прокрутки от прежнего ролика остаётся видимая полоска:
//      нулевой площади он достигает только на СЛЕДУЮЩЕЙ прокрутке.
//    С правилом «площадь 0» донесение опаздывало на целую прокрутку: новый ролик играл в браузере со звуком и
//    без заглушки, окно стояло на паузе, а запоздавший взвод сторожа хватал ролик, с которого уже уходили.
//
// 2. Тик часов плеера, пока ролик стоит (пауза или конец ролика) — прежнее строгое правило: ролика на экране
//    нет совсем (доля 0: за окном, вынут из документа или скрыт). Порог первой точки сюда не переносится
//    нарочно: на тике «стоит» — это ещё и доигранная серия или реклама, и доигравшая серия, которую человек
//    наполовину прокрутил к комментариям, не должна превращаться в «ленту» (у ожидания следующей серии свой
//    срок, решения 303 и 204). TikTok вынимает ролик из документа (доля 0) — он подходит под оба правила.
//
// Сторож — чистое правило без DOM: факты (доля ролика на экране, кто остановил) ему подаёт контроллер тени.
// Донесение одно на уход; следующее — только после того, как ролик вернулся на экран или страница его снова
// запустила.

/**
 * Какая доля площади ролика должна быть на экране, чтобы пауза страницы считалась паузой ролика «на экране».
 * Меньше — страница остановила уходящий ролик.
 *
 * Откуда число. Лента переключает ролик, когда следующий виден наполовину или больше; ролик ленты занимает
 * почти всю высоту окна, поэтому прежнему в этот миг остаётся не больше ~57 % (замер: 12–53 %). Ролик, который
 * человек смотрит, виден целиком. Три четверти стоят между ними с запасом в обе стороны: пауза ролика, видного
 * целиком или почти целиком, переезд не открывает.
 */
export const REEL_ON_SCREEN_SHARE = 0.75;

/** Что сделать после проверки. */
export type ScreenExitStep = "report_left_screen" | "nothing";

export class ScreenExitWatch {
  /** Об этом уходе уже донесено. */
  #reported = false;

  /** Страница видит ролик играющим: следующий уход с экрана — новое донесение. */
  notePlaying(): void {
    this.#reported = false;
  }

  /**
   * Страница только что позвала `pause()`. `visibleShare` — какая доля площади ролика сейчас на экране
   * (0..1): 0 — вне окна, вне документа или скрыт стилями. Меньше порога — страница остановила уходящий ролик.
   */
  notePausedByPage(visibleShare: number): ScreenExitStep {
    if (this.#backOnScreen(visibleShare)) return "nothing";
    return this.#reportOnce();
  }

  /**
   * Тик часов плеера, ролик стоит (пауза страницы или зрителя, конец ролика). Уходом считается только
   * ролик, которого на экране нет совсем (см. шапку, точка 2).
   */
  noteStoppedOnTick(visibleShare: number): ScreenExitStep {
    if (this.#backOnScreen(visibleShare) || visibleShare > 0) return "nothing";
    return this.#reportOnce();
  }

  /** Ролик снова на экране: следующий уход — новое донесение. Полоска уходящего ролика возвратом не считается. */
  #backOnScreen(visibleShare: number): boolean {
    if (visibleShare < REEL_ON_SCREEN_SHARE) return false;
    this.#reported = false;
    return true;
  }

  #reportOnce(): ScreenExitStep {
    if (this.#reported) return "nothing";
    this.#reported = true;
    return "report_left_screen";
  }
}
