// Возврат страницы на место (протокол 1.4, сессия 11b1, решения 240-241). Зеркало
// session/page_reopen.rs.
//
// Весь договор в одном месте:
// 1. Вкладка-источник исчезла, но экстеншен НЕ рвёт соединение: оставляет сеанс «сиротой»
//    (байтов больше нет) и шлёт `page_left{reason}`. Плеер продолжает слать `clock`.
// 2. Зритель нажимает play в плеере: плеер шлёт `reopen_page{position_us}`.
// 3. Экстеншен открывает страницу заново. Получилось - `page_returned` (тот же сеанс,
//    дальше НОВОЕ поколение). Не получилось - `page_reopen_failed{reason}` и закрытие
//    соединения кодом 4002 (`tab_gone`).
// 4. Если экстеншен вообще не может вернуть страницу, он по-прежнему шлёт `tab_gone`.
// Коды закрытия не менялись. Правила порядка сообщений проверяет сторож плеера (Rust).

/**
 * Почему экстеншен не смог вернуть страницу (`page_reopen_failed`). Метка строгая:
 * snake_case, без нормализации регистра; незнакомая - `unknown_value`.
 */
export type PageReopenFailure =
  /** Нет окна браузера, в котором можно открыть страницу. */
  | "no_browser_window"
  /** Страница не загрузилась (навигация закончилась ошибкой). */
  | "page_did_not_load"
  /** Страница открылась, но показывает другое видео (например, сайт-одностраничник). */
  | "not_the_same_video"
  /** Видео не запустилось за отведённое время. */
  | "video_did_not_start";

/** Все отказы возврата - один список для разбора и для таблицы версий. */
export const PAGE_REOPEN_FAILURES: readonly PageReopenFailure[] = [
  "no_browser_window",
  "page_did_not_load",
  "not_the_same_video",
  "video_did_not_start",
];
