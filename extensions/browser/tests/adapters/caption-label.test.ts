// Общая английская подпись субтитров (15a2): ею подписаны и пункты меню YouTube, и скачанный документ timedtext.
import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { nameSubtitleDocumentByAddress } from "../../src/adapters/registry/page-world.ts";
import { captionLabelOf } from "../../src/adapters/capabilities/subtitle-naming/caption-label.ts";
import { protocolNamingOf } from "../../src/background/handoff/page-subtitles/track-naming.ts";

const plain = { autoGenerated: false, autoTranslated: false } as const;

describe("captionLabelOf", () => {
  it("ручная, автосубтитры и автоперевод", () => {
    assert.equal(captionLabelOf({ language: "en", ...plain }), "English");
    assert.equal(captionLabelOf({ language: "en", autoGenerated: true, autoTranslated: false }), "English (auto-generated)");
    assert.equal(captionLabelOf({ language: "uk", autoGenerated: false, autoTranslated: true }), "Ukrainian (auto-translated)");
    assert.equal(captionLabelOf({ language: "zh-Hans", autoGenerated: false, autoTranslated: true }), "Simplified Chinese (auto-translated)");
  });

  it("перевод главнее распознавания; название дорожки идёт в скобках после языка", () => {
    assert.equal(captionLabelOf({ language: "de", autoGenerated: true, autoTranslated: true }), "German (auto-translated)");
    assert.equal(captionLabelOf({ language: "en", ...plain, trackName: "British" }), "English (British)");
    assert.equal(captionLabelOf({ language: "en", autoGenerated: true, autoTranslated: false, trackName: "Lyrics" }), "English (Lyrics) (auto-generated)");
  });

  it("языка или его названия нет: слова признака; у ручной дорожки без названия - пустая строка", () => {
    assert.equal(captionLabelOf({ language: null, autoGenerated: true, autoTranslated: false }), "Auto-generated");
    assert.equal(captionLabelOf({ language: "zzzzzzzz", autoGenerated: false, autoTranslated: true }), "Auto-translated");
    assert.equal(captionLabelOf({ language: null, ...plain }), "");
    assert.equal(captionLabelOf({ language: "bad tag", ...plain, trackName: "Mine" }), "Mine");
  });
});

describe("документ timedtext получает ту же подпись, что и пункт меню", () => {
  const timedtext = "https://www.youtube.com/api/timedtext?v=abcdefghijk&lang=en";

  it("tlang: путь от адреса до полей протокола даёт «<язык перевода> (auto-translated)»", () => {
    const naming = nameSubtitleDocumentByAddress(`${timedtext}&tlang=uk&fmt=json3`);
    assert.ok(naming);
    assert.deepEqual(protocolNamingOf(naming), { language: { kind: "known", tag: "uk" }, label: { kind: "text", text: "Ukrainian (auto-translated)" } });
    // Та же строка, что у пункта меню для этого языка.
    assert.equal(captionLabelOf({ language: "uk", autoGenerated: false, autoTranslated: true }), "Ukrainian (auto-translated)");
  });

  it("tlang поверх автосубтитров остаётся переводом; без tlang - подпись родной дорожки, как у строки меню", () => {
    const translatedAsr = nameSubtitleDocumentByAddress(`${timedtext}&kind=asr&tlang=de`);
    assert.ok(translatedAsr);
    assert.deepEqual(protocolNamingOf(translatedAsr).label, { kind: "text", text: "German (auto-translated)" });
    const asr = nameSubtitleDocumentByAddress(`${timedtext}&kind=asr`);
    assert.ok(asr);
    assert.deepEqual(protocolNamingOf(asr).label, { kind: "text", text: "English (auto-generated)" });
    const manual = nameSubtitleDocumentByAddress(timedtext);
    assert.ok(manual);
    assert.deepEqual(protocolNamingOf(manual).label, { kind: "text", text: "English" });
  });
});
