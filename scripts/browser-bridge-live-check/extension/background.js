// Одноразовый background для живой проверки посредника. Один файл для Chromium (service worker)
// и Firefox (background.scripts).
"use strict";
if (typeof importScripts === "function") { importScripts("config.js", "runner.js"); }
const api = typeof browser !== "undefined" ? browser : chrome;
const config = globalThis.LIVE_CONFIG || {};
// Имя хоста приходит из config.js (его пишет скрипт запуска из fixtures/extension-identity.json).
const HOST_NAME = config.hostName;
if (!HOST_NAME) { throw new Error("LIVE_CONFIG.hostName is not set (config.js not generated by the run script)"); }
const startedAt = Date.now();
let running = false;

function log(text) {
  const line = "[live +" + ((Date.now() - startedAt) / 1000).toFixed(2) + "s] " + text;
  console.log(line);
  postStatus({ logLine: line });
}

// Статус для скрипта запуска: POST text/plain (простой запрос, без preflight) на локальный сервер.
function postStatus(body) {
  if (!config.statusUrl) return;
  fetch(config.statusUrl, { method: "POST", headers: { "Content-Type": "text/plain" }, body: JSON.stringify(body) })
    .catch((e) => { console.log("status post failed: " + e); });
}

// Ответы посредника по порядку: каждый запрос получает ровно один ответ.
function openHostPort() {
  const port = api.runtime.connectNative(HOST_NAME);
  const waiting = [];
  const arrived = [];
  let closedReason = null;
  port.onMessage.addListener((message) => {
    log("host -> " + (message && message.type));
    const waiter = waiting.shift();
    if (waiter) waiter.resolve(message); else arrived.push(message);
  });
  port.onDisconnect.addListener((p) => {
    closedReason = (p && p.error && p.error.message) || (api.runtime.lastError && api.runtime.lastError.message) || "disconnected";
    log("host port disconnected: " + closedReason);
    while (waiting.length) waiting.shift().reject(new Error("host port closed: " + closedReason));
  });
  return {
    port,
    request(message) {
      log("-> host " + message.type);
      port.postMessage(message);
      return new Promise((resolve, reject) => {
        if (arrived.length) return resolve(arrived.shift());
        if (closedReason) return reject(new Error("host port closed: " + closedReason));
        waiting.push({ resolve, reject });
        setTimeout(() => reject(new Error("host did not answer " + message.type)), 30000);
      });
    },
  };
}

async function loadMedia(plan) {
  const media = {};
  for (const name of plan.files) {
    const response = await fetch(api.runtime.getURL("media/" + name));
    media[name] = new Uint8Array(await response.arrayBuffer());
    log("loaded " + name + " " + media[name].byteLength + " bytes");
  }
  return media;
}

async function runLiveCheck(trigger) {
  if (running) { log("already running, ignored " + trigger); return; }
  running = true;
  log("start (" + trigger + ")");
  let stats = { phase: "failed", error: "not started" };
  try {
    const plan = await (await fetch(api.runtime.getURL("plan.json"))).json();
    const media = await loadMedia(plan);
    const host = openHostPort();
    const hello = await host.request({
      type: "hello", protocol: { major: 1, minor: 0 }, software_version: "0.1.0", capabilities: [],
    });
    if (hello.type !== "hello_accepted") throw new Error("hello answered with " + JSON.stringify(hello));
    const granted = await host.request({
      type: "open_session", request_id: 1, session_key: "tab-1-video-" + (Date.now() % 100000),
      page: { title: "Bridge live check", domain: "localhost" },
      intent: "window",
      hints: { duration: { kind: "finite", duration_us: plan.duration_us }, position: { kind: "unknown" } },
    });
    if (granted.type !== "session_granted") throw new Error("open_session answered with " + JSON.stringify(granted));
    log("session granted port=" + granted.port + " outcome=" + granted.outcome);
    stats = await BridgeLive.playStream({
      url: "ws://127.0.0.1:" + granted.port + "/",
      attach: { session_key: granted.session_key, token: granted.token },
      plan, media, log,
      report: (snapshot) => postStatus({ stats: snapshot }),
    });
    // Порт остаётся открытым до закрытия браузера (проверка «хост выходит по EOF»);
    // config.disconnectHost = true — как закрытая вкладка.
    if (config.disconnectHost) host.port.disconnect();
  } catch (error) {
    stats.error = String(error && error.message || error);
    log("ERROR " + stats.error);
  }
  running = false;
  postStatus({ stats, final: true });
}

api.runtime.onInstalled.addListener(() => runLiveCheck("onInstalled"));
api.runtime.onStartup.addListener(() => runLiveCheck("onStartup"));
api.action.onClicked.addListener(() => runLiveCheck("toolbar click"));
