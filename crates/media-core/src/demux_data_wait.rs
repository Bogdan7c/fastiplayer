//! Чего ждёт демуксер, когда отвечает `TemporarilyUnavailable`.
//!
//! Обычный источник (файл на диске, сетевой поток со своими повторами) ждёт
//! только задержку ввода: если данных нет долго, это сбой, и плеер стережёт его
//! сроком перемотки (`player.seek.commit_timeout_ms`). Но бывает источник, которому
//! байты приносит **живой поставщик** — страница браузера, у которой свой плеер и
//! своя сеть (мост, решение владельца 150). Такой поставщик может нести данные
//! нового места дольше срока плеера (YouTube 4K отдавал место через 12 с), и это не
//! сбой: браузер в этом случае просто крутит спиннер, пока данные не придут.
//!
//! Источник говорит об этом сам, через [`crate::Demuxer::data_wait`]: «если я
//! сейчас отвечаю `TemporarilyUnavailable`, это потому, что поставщик ещё на связи и
//! несёт данные». Плеер, увидев на своём последнем чтении `TemporarilyUnavailable`
//! И такой ответ, не засчитывает это время в срок перемотки. Как только данные
//! есть (чтение отдаёт пакеты), срок снова идёт: застрявший у плеера декодер или
//! звук после прихода данных — настоящий сбой, и защита срабатывает как раньше.
//!
//! **Предел молчания (решение 151).** Вместе с ответом источник отдаёт счётчик
//! [`LiveProducerProgress`] — сколько поставщик уже принёс для данных, которых ждёт
//! плеер. Пока счётчик растёт, ожидание без предела; если он не менялся дольше
//! `player.seek.live_source_stall_timeout_ms` (60 с), плеер честно сдаётся
//! («Seeking timed out»): страница на связи, но цель не несёт.
//!
//! Обёртка, которая уносит внутренний демуксер в другой поток (фоновое чтение),
//! спросить его оттуда не может; для неё есть [`DemuxDataWaitProbe`] — потокобезопасный
//! вопрос, который внутренний демуксер отдаёт заранее ([`crate::Demuxer::data_wait_probe`]).

use std::fmt;
use std::sync::Arc;

/// Сколько живой поставщик уже принёс для данных, которых ждёт плеер (байты).
///
/// Монотонный счётчик: плееру важно только, изменился ли он с прошлого ответа.
/// Что именно считается «принесённым для ожидаемого», определяет источник и
/// документирует у себя.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Default)]
pub struct LiveProducerProgress(u64);

impl LiveProducerProgress {
    /// Счётчик по числу принесённых байтов.
    #[must_use]
    pub const fn from_delivered_bytes(bytes: u64) -> Self {
        Self(bytes)
    }

    /// Сколько байтов принесено.
    #[must_use]
    pub const fn delivered_bytes(self) -> u64 {
        self.0
    }
}

/// Почему у демуксера сейчас нет данных (смысл его `TemporarilyUnavailable`).
///
/// По умолчанию ([`crate::Demuxer::data_wait`]) — [`DemuxDataWait::Unattributed`]:
/// у обычных файлов и сетевых источников поведение плеера не меняется.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum DemuxDataWait {
    /// Источник ничего не уточняет: ожидание — задержка ввода, долгое ожидание —
    /// сбой, его стережёт срок плеера.
    Unattributed,
    /// Недостающие данные несёт живой поставщик, который всё ещё на связи
    /// (страница браузера не ушла, поток не оборван и не сломан): ожидание честное,
    /// пока растёт `progress`. Поставщик ушёл — источник отвечает
    /// [`DemuxDataWait::Unattributed`] (дальше — обычный конец данных).
    LiveProducer {
        /// Что поставщик уже принёс для ожидаемых данных.
        progress: LiveProducerProgress,
    },
}

impl DemuxDataWait {
    /// Ждём ли живого поставщика (любой счётчик).
    #[must_use]
    pub const fn is_live_producer(self) -> bool {
        matches!(self, Self::LiveProducer { .. })
    }
}

/// Потокобезопасный вопрос «чего ждёт источник» — для обёрток, которые держат
/// внутренний демуксер в другом потоке.
#[derive(Clone)]
pub struct DemuxDataWaitProbe(Arc<dyn Fn() -> DemuxDataWait + Send + Sync>);

impl DemuxDataWaitProbe {
    /// Вопрос из замыкания (замыкание не должно ждать и блокироваться надолго:
    /// его зовут с потока плеера).
    #[must_use]
    pub fn new(query: impl Fn() -> DemuxDataWait + Send + Sync + 'static) -> Self {
        Self(Arc::new(query))
    }

    /// Ответ источника сейчас.
    #[must_use]
    pub fn data_wait(&self) -> DemuxDataWait {
        (self.0)()
    }
}

impl fmt::Debug for DemuxDataWaitProbe {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str("DemuxDataWaitProbe")
    }
}
