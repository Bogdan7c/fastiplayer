//! Где на самом деле кончились данные демуксера, отдавшего `EndOfStream`.
//!
//! Обычно конец потока — это конец медиа: файл дочитан, страница честно сказала
//! «больше нет». Но бывает, что источник перестал получать данные раньше конца
//! медиа: браузерная вкладка ушла посреди скачивания, и плеер доигрывает только то,
//! что успело прийти. Тогда `EndOfStream` значит «полученное кончилось», а не «фильм
//! кончился», и плееру нельзя ставить позицию в длительность фильма — зритель
//! увидел бы прыжок ползунка в конец.
//!
//! Если источник знает, до какого времени у него есть данные всех дорожек сразу, он
//! сообщает это время: плеер мог прочитать впрок дальше (звук, выданный раньше, чем
//! источник узнал об обрыве), и останавливает показ сам, дойдя часами до этого времени.
//! Если время неизвестно (файл, обрезанный посреди байтов), плеер ставит позицию там,
//! где встали его часы показа.

use std::time::Duration;

/// Каким был конец данных демуксера на его `EndOfStream`.
///
/// Плеер спрашивает по ходу показа и когда доиграл до конца. По умолчанию
/// ([`crate::Demuxer::data_end`]) — [`DemuxDataEnd::Complete`]: у обычных файлов и
/// сетевых источников поведение не меняется.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum DemuxDataEnd {
    /// Данные кончились там, где кончается медиа: конец потока — конец фильма.
    Complete,
    /// Источник перестал получать данные раньше конца медиа (например, страница,
    /// которая приносила байты, ушла): конец потока — конец полученного, а
    /// длительность медиа больше того, что можно сыграть.
    CutShort {
        /// До какого момента шкалы медиа есть данные всех дорожек сразу; дальше
        /// играть нечего, даже если плеер успел прочитать больше. `None` — источник
        /// этого не знает: конец там, где кончились прочитанные данные.
        playable_end: Option<Duration>,
    },
}
