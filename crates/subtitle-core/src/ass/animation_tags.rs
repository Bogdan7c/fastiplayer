//! Тег анимации `\t` в сыром виде (ass_parse.c, ветка `complex_tag("t")`).
//!
//! Модель хранит ТОЛЬКО то, что написано в файле, уже разобранное по правилам libass для
//! каждого числа аргументов. Вычисление прогресса `k` (зависит от времени кадра и длительности
//! реплики) и применение вложенных тегов с коэффициентом `pwr = k` — дело растеризатора.

use super::overrides::AssOverride;

/// Времена и ускорение `\t`, как их читает libass в зависимости от числа аргументов
/// (`cnt = nargs - 1`, где `nargs` — число непустых аргументов, включая аргумент с тегами).
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum AssTransformTiming {
    /// `\t(\теги)`, а также любые некорректные формы: `t1 = t2 = 0`, `accel = 1`.
    /// Нулевой `t2` растеризатор превращает в длительность реплики.
    Default,
    /// `\t(accel,\теги)`: `t1 = t2 = 0`, ускорение — `argtod(arg0)`.
    Accel(f64),
    /// `\t(t1,t2,\теги)`: VSFilter читает времена как дробные числа (`dtoi32(argtod)`,
    /// поэтому допустимы `500.5` и `1e3`); `accel = 1`.
    Range { t1_ms: i32, t2_ms: i32 },
    /// `\t(t1,t2,accel,\теги)`: времена — целые (`argtoi32`), ускорение — `argtod`.
    RangeAccel { t1_ms: i32, t2_ms: i32, accel: f64 },
}

/// Тег `\t(...)`.
///
/// Даже «пустой» `\t` (нет вложенных тегов, неверное число аргументов) сохраняется, потому что
/// libass всё равно: (1) выключает поиск свободного места для реплики (`detect_collisions = 0`),
/// (2) внутри другого `\t` заменяет коэффициент `pwr` для идущих следом тегов. Для таких
/// тегов [`AssTransform::tags`] пуст, а [`AssTransform::timing`] посчитан по тем же правилам
/// (`Default` для некорректных форм).
#[derive(Debug, Clone, PartialEq)]
pub struct AssTransform {
    pub timing: AssTransformTiming,
    /// Вложенные теги в порядке записи. Разбираются тем же разбором, что и блок реплики;
    /// вложенный `\t` допустим (его коэффициент ЗАМЕНЯЕТ внешний, а не перемножается).
    pub tags: Vec<AssOverride>,
}
