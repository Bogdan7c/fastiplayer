//! Типы тегов слоя 3: клипы `\clip`/`\iclip` и ограничения размытия.
//!
//! Значения хранятся «как написано» (с семантикой аргументов libass 0.17.5). Правила,
//! зависящие от состояния реплики («последний прямоугольный клип побеждает», «первый
//! векторный клип побеждает», зажатие `\blur` и `\be`), применяет растеризатор: это нужно,
//! потому что `\t` (анимация) интерполирует сырое значение ДО зажатия.

/// Верхняя граница радиуса `\blur` (`BLUR_MAX_RADIUS` в `ass_parse.h`).
pub const ASS_BLUR_MAX_RADIUS: f64 = 100.0;

/// Верхняя граница `\be` после округления (`MAX_BE` в `ass_parse.c`).
pub const ASS_EDGE_BLUR_MAX: i32 = 127;

/// Режим клипа: что остаётся видимым.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum AssClipMode {
    /// `\clip`: видно только внутри фигуры.
    Inside,
    /// `\iclip`: видно только снаружи фигуры.
    Outside,
}

/// Форма клипа.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum AssClipShape {
    /// `\clip(x0,y0,x1,y1)`: ровно четыре аргумента; целые числа (`argtoi32`) в координатах
    /// `PlayRes`. Порядок углов не нормализуется (это делает растеризатор, как libass).
    Rect { x0: i32, y0: i32, x1: i32, y1: i32 },
    /// `\clip([scale,]рисунок)`: один или два аргумента. `scale` по умолчанию 1; точность
    /// координат рисунка `2^(scale-1)`, как у `\p`. `drawing` — текст команд рисования
    /// (`m 0 0 l ...`) без обратных косых черт, дословно как в файле (без пробелов по краям).
    Vector { scale: i32, drawing: String },
}

/// Разобранный `\clip` или `\iclip`.
///
/// libass хранит ОДИН прямоугольный клип (побеждает последний тег) и ОДИН векторный
/// (побеждает первый) одновременно; парсер сохраняет все вхождения по порядку.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct AssClip {
    pub mode: AssClipMode,
    pub shape: AssClipShape,
}
