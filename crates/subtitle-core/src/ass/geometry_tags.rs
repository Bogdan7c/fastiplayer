//! Типы тегов геометрии и затухания слоя 2: повороты, наклон, затухание.
//!
//! Значения хранятся «как написано» (с семантикой аргументов libass 0.17.5). Правила,
//! зависящие от состояния реплики («первый `\org` побеждает», «`\fad` переписывается
//! через длительность реплики»), применяет растеризатор.

/// Ось поворота: `\frx`, `\fry`, `\frz` (и `\fr` = `\frz`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum AssRotationAxis {
    /// `\frx`: вокруг горизонтальной оси (текст «ложится назад»).
    X,
    /// `\fry`: вокруг вертикальной оси.
    Y,
    /// `\frz`, `\fr`: в плоскости кадра.
    Z,
}

/// Ось наклона: `\fax` (горизонтальный сдвиг) и `\fay` (вертикальный).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum AssShearAxis {
    /// `\fax`: сдвиг по горизонтали пропорционально высоте.
    X,
    /// `\fay`: сдвиг по вертикали пропорционально ширине.
    Y,
}

/// Затухание `\fad`/`\fade` в сыром виде (до пересчёта через длительность реплики).
///
/// libass при двух аргументах строит `a1=255, a2=0, a3=255, t1=-1, t4=-1`; при `t1 == -1`
/// и `t4 == -1` времена переписываются как `t1=0, t4=Duration, t3=Duration-t3`. Длительность
/// реплики парсеру недоступна, поэтому пересчёт делает растеризатор.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum AssFade {
    /// `\fad(вход, выход)`: длительности появления и угасания в миллисекундах.
    Simple {
        /// Аргумент `t2`: сколько миллисекунд реплика появляется.
        fade_in_ms: i32,
        /// Аргумент `t3` до пересчёта: сколько миллисекунд реплика угасает.
        fade_out_ms: i32,
    },
    /// `\fade(a1,a2,a3,t1,t2,t3,t4)`: три уровня прозрачности (0..255) и четыре момента.
    Full {
        /// Прозрачность до `t1`, между `t2` и `t3`, после `t4`.
        alphas: [i32; 3],
        /// Моменты `t1..t4` в миллисекундах от начала реплики.
        times_ms: [i32; 4],
    },
}
