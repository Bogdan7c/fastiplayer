//! Диапазоны памяти встроенных дорожек PGS (схема v22): бюджет показываемой дорожки и окно
//! фоновых дорожек. Вынесены отдельным модулем, чтобы файл схемы `[subtitles]` не раздувался;
//! публичный путь констант - `pub use` в `schema.rs`.
//!
//! PGS хранит картинки (RLE + палитра), а не текст, поэтому лимит «число реплик» для него
//! бессмыслен: память ограничивается в мегабайтах и во времени.

/// Бюджет кэша показываемой дорожки PGS, МБ, по умолчанию. Решение владельца (сессия 11):
/// 32 МБ. Для типичного фильма это весь кэш дорожки (сжатые картинки занимают единицы МБ),
/// поэтому перемотка назад показывает субтитры из кэша без повторного чтения.
pub const DEFAULT_PGS_DISPLAYED_TRACK_CACHE_MB: u16 = 32;
/// Минимум: 1 МБ. Меньше не вмещает даже несколько полноэкранных наборов отображения.
pub const MIN_PGS_DISPLAYED_TRACK_CACHE_MB: u16 = 1;
/// Максимум: 1024 МБ. Потолок защищает от опечатки; больше любого реального фильма.
pub const MAX_PGS_DISPLAYED_TRACK_CACHE_MB: u16 = 1_024;

/// Окно хвоста фоновых дорожек PGS, секунд, по умолчанию. Решение владельца (сессия 11):
/// 60 с. Фоновая дорожка хранит только последнюю минуту перед позицией воспроизведения, чтобы
/// быстрое переключение дорожки показало картинку сразу, а память не росла на весь фильм.
pub const DEFAULT_PGS_BACKGROUND_TRACK_WINDOW_S: u16 = 60;
/// Минимум: 0 с. Фоновая дорожка не хранит ничего позади позиции воспроизведения.
pub const MIN_PGS_BACKGROUND_TRACK_WINDOW_S: u16 = 0;
/// Максимум: 3600 с (час). Дольше смысла нет: за час сжатые картинки одной дорожки укладываются
/// в бюджет показываемой.
pub const MAX_PGS_BACKGROUND_TRACK_WINDOW_S: u16 = 3_600;
