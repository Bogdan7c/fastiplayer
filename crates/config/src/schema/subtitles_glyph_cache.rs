//! Диапазоны кэшей глифов растеризатора субтитров (схема v21): общий объём масок и число
//! записей кэша контуров. Вынесены отдельным модулем, чтобы файл схемы `[subtitles]` не
//! раздувался; публичный путь констант - `pub use` в `schema.rs`.

/// Общий объём кэшей масок глифов, МБ, по умолчанию. Делится как в libass: две трети - кэш
/// масок отдельных глифов, треть - кэш склеек участков. Решение владельца (сессия 10c): 64 МБ.
pub const DEFAULT_GLYPH_CACHE_MB: u16 = 64;
/// Минимум: 8 МБ. Меньше не вмещает рабочий набор одного кадра с тяжёлым караоке, и кэш
/// превратился бы в формальность.
pub const MIN_GLYPH_CACHE_MB: u16 = 8;
/// Максимум: 1024 МБ. Потолок защищает от опечатки; больше любой практичной сцены.
pub const MAX_GLYPH_CACHE_MB: u16 = 1_024;

/// Записей кэша контуров глифов по умолчанию (как `glyph_max` libass).
pub const DEFAULT_GLYPH_OUTLINE_CACHE_ITEMS: u32 = 10_000;
/// Минимум: 256 записей хватает на латинский алфавит нескольких стилей и рисунки одной сцены.
pub const MIN_GLYPH_OUTLINE_CACHE_ITEMS: u32 = 256;
/// Максимум: 200 000 записей. Контуры малы (сотни байт), но потолок защищает от опечатки.
pub const MAX_GLYPH_OUTLINE_CACHE_ITEMS: u32 = 200_000;

/// Память кэша результатов шейпинга (участки текста -> глифы), МБ, по умолчанию.
///
/// Запись - один участок единого вида: ключ (текст) плюс ~24 байта на глиф, то есть порядка
/// 0.3-1 КБ на реплику. 4 МБ - это тысячи участков: больше любого реального набора реплик на
/// экране за несколько секунд, а у libass такого кэша нет вовсе (шейпинг каждый кадр).
pub const DEFAULT_SHAPING_CACHE_MB: u16 = 4;
/// Минимум: 1 МБ - несколько сотен участков, достаточно для одной сцены с караоке.
pub const MIN_SHAPING_CACHE_MB: u16 = 1;
/// Максимум: 256 МБ. Потолок защищает от опечатки; цельный фильм с ~2000 репликами помещается
/// в единицы мегабайт, так что больше смысла не имеет.
pub const MAX_SHAPING_CACHE_MB: u16 = 256;
