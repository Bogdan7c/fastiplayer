//! Константы и перечисления ASS/SSA-части секции `[subtitles]` (схема v18).
//!
//! Поля самой секции живут в `SubtitlesConfig` (`schema/subtitles.rs`), а здесь — то, что
//! не нужно раздувать в большом файле: режим позиции ASS-слоя и диапазоны лимитов разбора.
//!
//! Решение владельца (субтитры, сессия 08): ASS всегда привязан к картинке видео;
//! режим позиции решает, что приложение двигает: только основной диалог (поднимает над
//! панелью управления, надписи стоят), весь слой (подъём и сдвиг пользователя) или ничего.

use serde::{Deserialize, Serialize};

/// Как приложение размещает слой ASS/SSA-субтитров на картинке.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum AssPositionMode {
    /// По умолчанию: основные реплики (без `\pos`/`\move`, выравнивание снизу) плавно
    /// поднимаются над панелью управления, пока она видна, и возвращаются на авторское место
    /// при её скрытии. Надписи и верхние реплики не двигаются; сдвиг пользователя к ASS не
    /// применяется. Всё остаётся внутри картинки.
    MainLinesAvoidControls,
    /// Слой не двигается: ни подъёма над панелью, ни сдвига пользователя (как в mpv).
    Author,
    /// Весь слой двигается как обычные субтитры, но не выходит за картинку.
    WholeLayer,
}

/// Лимит заголовка ASS (`[Script Info]` + стили + шрифты-вложения в тексте), КБ, по умолчанию.
pub const DEFAULT_MAX_ASS_HEADER_KB: u32 = 1_024;
/// Минимальный лимит заголовка ASS, КБ.
pub const MIN_MAX_ASS_HEADER_KB: u32 = 64;
/// Максимальный лимит заголовка ASS, КБ.
pub const MAX_MAX_ASS_HEADER_KB: u32 = 16_384;

/// Сколько стилей принимается из одного ASS-заголовка, по умолчанию.
pub const DEFAULT_MAX_ASS_STYLES: u32 = 1_000;
/// Минимальное число стилей.
pub const MIN_MAX_ASS_STYLES: u32 = 10;
/// Максимальное число стилей.
pub const MAX_MAX_ASS_STYLES: u32 = 10_000;

/// Сколько ASS-событий одновременно рисуется на кадре, по умолчанию (сложная типографика
/// держит на экране десятки и сотни событий одновременно, поэтому лимит выше, чем у текста).
pub const DEFAULT_MAX_ASS_EVENTS_ON_SCREEN: u32 = 256;
/// Минимальное число одновременных ASS-событий.
pub const MIN_MAX_ASS_EVENTS_ON_SCREEN: u32 = 16;
/// Максимальное число одновременных ASS-событий.
pub const MAX_MAX_ASS_EVENTS_ON_SCREEN: u32 = 2_048;

/// Сколько тегов `{\...}` читается из одной реплики, по умолчанию.
pub const DEFAULT_MAX_ASS_OVERRIDE_TAGS_PER_EVENT: u32 = 512;
/// Минимальное число тегов в реплике.
pub const MIN_MAX_ASS_OVERRIDE_TAGS_PER_EVENT: u32 = 32;
/// Максимальное число тегов в реплике.
pub const MAX_MAX_ASS_OVERRIDE_TAGS_PER_EVENT: u32 = 8_192;
