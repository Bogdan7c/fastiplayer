//! Типизированные итоги чтения и записи «общей доски» config-а.
//!
//! Различия, которые вызывающему коду важны, не сливаются в `bool`: «записано» и
//! «записано без подтверждения надёжности», «замок занят» и «замок нельзя использовать»,
//! «файл на диске битый» и «файл от новой версии» — разные варианты.

use std::io;
use std::time::Duration;

use atomic_file_store::DirectorySyncError;

use crate::{AppConfig, BrokenConfigProblem, ConfigError, ConfigWriteProblem};

/// Что сейчас лежит в config-файле — для слежения соседних копий плеера.
///
/// Результат чтения без замка и без побочных эффектов: файл не создаётся, не
/// переименовывается и не чинится.
#[derive(Debug, Clone, PartialEq)]
pub enum SharedConfigRead {
    /// Файл прочитан и прошёл строгую проверку (с миграциями старых версий).
    Parsed(Box<AppConfig>),
    /// Файла нет.
    Missing,
    /// Файл есть, но использовать его нельзя.
    Unreadable {
        /// Почему файл нельзя использовать.
        problem: SharedConfigProblem,
    },
    /// Файл записан более новой версией плеера; трогать его нельзя.
    Newer {
        /// Версия схемы, найденная в файле.
        found: i64,
    },
}

/// Почему config-файл на диске нельзя взять за основу.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SharedConfigProblem {
    /// Файл повреждён: синтаксис, неизвестный ключ, значение вне диапазона.
    Broken(BrokenConfigProblem),
    /// По пути config-а лежит не обычный файл (каталог, FIFO и т. п.).
    NotRegularFile,
    /// Файл есть, но прочитать его нельзя (права, ошибка диска).
    ReadFailed {
        /// Безопасный класс I/O ошибки (без пути).
        error_kind: io::ErrorKind,
    },
    /// Разбор упал не из-за содержимого файла (ошибка программы, а не пользователя).
    ///
    /// Практически недостижимо: проверка config-а сообщает только «значение вне
    /// диапазона». Файл в этом случае не трогается, как и при остальных проблемах.
    UnclassifiedParseFailure,
}

/// Итог одной попытки «перечитать → вписать свои ключи → записать» под замком.
///
/// `E` — ошибка функции слияния вызывающего кода (например, ошибка реестра настроек).
/// Во всех вариантах, кроме `Written*`, файл на диске остался байт-в-байт прежним.
#[derive(Debug)]
#[must_use = "the outcome tells whether the change reached the settings file"]
pub enum SharedConfigUpdate<E> {
    /// Записано, и каталог подтвердил надёжность записи.
    Written {
        /// Документ, который теперь лежит в файле.
        written: Box<AppConfig>,
    },
    /// Записано и читается, но sync каталога не подтверждён (сбой питания мог бы
    /// откатить запись). Предупреждение, а не провал.
    WrittenDurabilityUnconfirmed {
        /// Документ, который теперь лежит в файле.
        written: Box<AppConfig>,
        /// Какой шаг подтверждения не удался.
        sync_error: DirectorySyncError,
    },
    /// Замок держит другая копия плеера дольше срока ожидания.
    LockBusy {
        /// Сколько ждали до отказа.
        waited: Duration,
    },
    /// Замок нельзя использовать: подменён, чужой, не файл или ошибка ввода-вывода.
    LockUnavailable(SharedConfigLockProblem),
    /// Файл на диске нельзя взять за основу (битый, не файл, не читается).
    DiskConfigUnusable(SharedConfigProblem),
    /// Файл на диске записан более новой версией плеера.
    DiskConfigNewer {
        /// Версия схемы, найденная в файле.
        found: i64,
    },
    /// Функция слияния вызывающего кода отказалась вписывать изменения.
    MergeRejected(E),
    /// Документ после слияния не прошёл проверку или контроль сериализации
    /// (например, свой ключ несовместим с ключом, который сосед уже записал).
    MergedConfigRejected(ConfigError),
    /// Запись файла не удалась; прежний файл (если был) остался целым.
    WriteFailed(ConfigWriteProblem),
}

/// Почему не удалось взять замок записи config-а.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ConfigLockFailure {
    /// Замок держит другой писатель дольше срока ожидания.
    Busy {
        /// Сколько ждали до отказа.
        waited: Duration,
    },
    /// Замок нельзя использовать.
    Unavailable(SharedConfigLockProblem),
}

/// Почему файл-замок нельзя использовать.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SharedConfigLockProblem {
    /// По пути замка лежит не обычный файл: символическая ссылка, каталог, FIFO.
    NotRegularFile,
    /// Файл-замок принадлежит другому пользователю.
    OwnerMismatch,
    /// Между открытием и захватом путь замка стал указывать на другой файл.
    IdentityChanged,
    /// Ошибка ввода-вывода на одном из шагов.
    Io {
        /// Шаг, на котором произошла ошибка.
        stage: SharedConfigLockStage,
        /// Безопасный класс I/O ошибки (без пути).
        error_kind: io::ErrorKind,
    },
}

/// Шаг взятия замка, на котором произошла ошибка ввода-вывода.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SharedConfigLockStage {
    /// Создание каталога config-а.
    CreateDirectory,
    /// Проверка пути замка до открытия.
    InspectPath,
    /// Открытие или создание файла-замка.
    Open,
    /// Проверка уже открытого файла-замка.
    InspectDescriptor,
    /// Установка прав 0600 на файл-замок.
    RestrictPermissions,
    /// Сам захват замка.
    Acquire,
    /// Повторная проверка пути замка после захвата.
    RevalidatePath,
}
