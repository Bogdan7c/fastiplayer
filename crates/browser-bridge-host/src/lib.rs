//! Посредник native messaging `fastiplayer-browser-host` (мост в браузер, сессия 05).
//!
//! Посредник — «звонок в дверь» (решение 85):
//!
//! ```text
//!  браузер ─ argv: кто позвал ─► caller: наш экстеншен? нет → выход, шину не трогаем
//!  stdin  ─ 4 байта длины + JSON ─► framing ─► relay: строгий разбор hello / open_session
//!                                               │
//!                                               ▼
//!                                  door (trait PlayerDoor) ── D-Bus ──► плеер
//!                                               │      (будит его активацией)
//!  stdout ◄─ 4 байта длины + JSON ◄─ framing ◄──┘  ответ плеера или свой отказ
//! ```
//!
//! Всё живое (байты видео, MSE-события, часы, команды) идёт по WebSocket из
//! background экстеншена прямо в процесс браузерного режима, мимо посредника.
//! Поэтому посредник может умереть в любой момент — сеанс продолжится, а
//! состояния, которое нельзя потерять, у него нет.
//!
//! Модули — каждый владеет одним:
//! - [`caller`] — кто запустил посредника (argv Chrome и Firefox);
//! - [`framing`] — рамки native messaging и их пределы;
//! - [`door`] — шов к плееру: trait и реализация на клиенте D-Bus;
//! - [`relay`] — одно сообщение браузера → один ответ;
//! - [`host`] — цикл жизни посредника и код выхода;
//! - [`log`] — безопасный журнал в stderr (только виды событий и размеры).

pub mod caller;
pub mod door;
pub mod framing;
pub mod host;
pub mod log;
pub mod relay;
