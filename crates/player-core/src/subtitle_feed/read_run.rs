//! Номер прохода чтения демуксера для пакетов субтитров.

/// Номер прохода чтения демуксера; растёт при каждом seek/перезапуске чтения.
///
/// Пакеты одного прохода идут подряд без пропусков по времени (демуксер читает файл
/// последовательно), поэтому потребитель может считать, что внутри прохода «дыр» нет, а
/// смена номера означает разрыв: позиция чтения прыгнула (seek вперёд или назад, scrub,
/// перезапуск чтения), и между последним пакетом прежнего прохода и первым нового
/// пропущенный участок неизвестен.
///
/// Нумерация сквозная для всей трубы (не сбрасывается при смене media) и МОНОТОННАЯ.
/// Потребитель сравнивает номера порядково внутри одного `media_instance_id`: больше
/// известного — разрыв (и для всех дорожек media сразу); меньше известного — пакет остался
/// в трубе от времени до seek и должен быть отброшен (раньше сравнивалось только «равно /
/// не равно»). Номер растёт и когда труба теряет пакет из-за переполнения: потерянный
/// пакет — дыра, ближайший принятый начинает новый проход. Текущий номер доступен
/// потребителю и без пакетов — в `PlayerSnapshot::subtitle_read_run`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct SubtitleReadRun(u64);

impl SubtitleReadRun {
    /// Номер, с которого начинает любая труба.
    pub const INITIAL: Self = Self(0);

    /// Числовое значение (для логов и тестов).
    #[must_use]
    pub const fn get(self) -> u64 {
        self.0
    }

    /// Следующий проход. Насыщение на `u64::MAX` недостижимо на практике и безопасно:
    /// максимум, что случится, — два прохода получат один номер.
    ///
    /// Открыт для потребителей трубы: тесты приложения воспроизводят смену прохода (seek), не
    /// запуская демуксер.
    #[must_use]
    pub const fn next(self) -> Self {
        Self(self.0.saturating_add(1))
    }
}
