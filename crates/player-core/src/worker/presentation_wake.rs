//! Пробуждение UI-потока по факту «есть что показать» (cpu-parity, сессия 04).
//!
//! До сессии 04 UI узнавал о новом кадре и о событиях плеера (смена состояния, seek,
//! ошибка) только на очередном vsync-redraw: worker клал кадр в слот показа и события в
//! очередь молча. Теперь UI рисует кадр по событию, а не по vsync, поэтому worker обязан
//! будить его сразу после публикации.
//!
//! Контракт такой же, как у [`super::PlayerWorkerTimelineWake`]: без payload. Кадр уже лежит
//! в слоте показа, события — в очереди, snapshot — в latest-канале; пробуждение только
//! говорит «забери». Несколько публикаций подряд приложение сливает в одно пробуждение.

/// Минимальный bridge «worker → UI-поток»: payload остаётся в слотах и очередях worker-а.
pub trait PlayerWorkerPresentationWake: Send + Sync {
    /// Будит UI после того, как новый кадр показа или событие плеера уже опубликованы.
    ///
    /// Вызывается с потока worker-а; реализация обязана быть неблокирующей и дешёвой
    /// (атомарный флаг + отправка user event в event loop).
    fn wake_presentation(&self);
}
