//! Происхождение шкалы ролика: был ли он эфиром при открытии (мост 16d1, решение 328).
//!
//! Эфир, который кончился посреди просмотра, становится записью (`TimelineMode::Static`), но
//! его время по-прежнему отсчитано от окна эфира. При следующем открытии законченный
//! плейлист встанет с другим отсчётом (с нуля от начала последнего окна), поэтому место
//! такого ролика запоминать и восстанавливать нельзя. Вид шкалы сейчас (`TimelineMode`)
//! этого не говорит — говорит происхождение.

/// Каким ролик был при открытии.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash)]
pub enum TimelineOrigin {
    /// Запись (файл, VOD, MSE с длиной) — или ролика нет.
    #[default]
    Recording,
    /// Эфир; остаётся эфиром по происхождению и после того, как эфир кончился.
    Live,
}

impl TimelineOrigin {
    /// Время ролика отсчитано от окна эфира: место нельзя переносить в следующее открытие.
    #[must_use]
    pub const fn opened_as_live(self) -> bool {
        matches!(self, Self::Live)
    }
}
