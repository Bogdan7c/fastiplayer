fn player_update_from_settings(
    current: &AppConfig,
    affected_settings: &[SettingId],
) -> PlayerCommittedSettingsUpdate {
    let mut player_core = PlayerRuntimeSettingsUpdate::empty();
    let mut tick_settings = Vec::new();
    let mut decoder_settings = Vec::new();
    let mut deferred_settings = Vec::new();
    let mut default_volume_changed = false;
    let mut audio_output_device_changed = false;
    let mut video_backend_changed = false;

    for setting_id in affected_settings {
        let setting_name = setting_id.as_str();
        if setting_name == "audio.output_device" {
            audio_output_device_changed = true;
            continue;
        }
        if setting_name == "video.preferred_backend" {
            video_backend_changed = true;
            continue;
        }

        match player_runtime_setting_id(setting_name) {
            Some(PlayerRuntimeSettingId::AudioDefaultVolume) => {
                default_volume_changed = true;
            }
            Some(runtime_id) if player_decoder_ready_queue_setting(setting_name) => {
                tick_settings.push(runtime_id);
                decoder_settings.push(runtime_id);
            }
            Some(runtime_id) if player_tick_setting(setting_name) => {
                tick_settings.push(runtime_id);
            }
            Some(runtime_id) if player_decoder_thread_setting(setting_name) => {
                decoder_settings.push(runtime_id);
            }
            Some(runtime_id) => {
                player_core = player_core.with_unsupported_settings([runtime_id]);
                deferred_settings.push(setting_id.clone());
            }
            None => deferred_settings.push(setting_id.clone()),
        }
    }

    if !tick_settings.is_empty() {
        player_core = player_core.with_tick_config(PlayerTickConfig::from(current), tick_settings);
    }
    if default_volume_changed {
        player_core = player_core.with_default_volume(
            current.audio.volume as f32,
            [PlayerRuntimeSettingId::AudioDefaultVolume],
        );
    }
    if !decoder_settings.is_empty() {
        player_core = player_core.with_decoder_thread_config(
            PlayerWorkerConfig::decoder_thread_config_from_app_config(current),
            decoder_settings,
        );
    }
    if video_backend_changed {
        player_core = player_core.with_video_backend([PlayerRuntimeSettingId::VideoPreferredBackend]);
    }

    PlayerCommittedSettingsUpdate {
        player_core,
        audio_output_device_id: audio_output_device_changed
            .then(|| current.audio.output_device.clone()),
        deferred_boundary_settings: deferred_settings,
    }
}

fn runtime_route_from_descriptor(
    descriptor: &SettingDescriptor,
) -> SettingsResult<AppRuntimeRoute> {
    runtime_route_from_metadata(
        &descriptor.route,
        descriptor.id.as_str(),
        descriptor.apply_mode,
    )
}

fn runtime_route_from_update_setting(
    route: &SettingRouteId,
    setting_id: &str,
) -> SettingsResult<AppRuntimeRoute> {
    let apply_mode = if render_preview_setting(setting_id) {
        SettingApplyMode::ImmediatePreview
    } else {
        SettingApplyMode::CommittedApply
    };

    runtime_route_from_metadata(route, setting_id, apply_mode)
}

fn runtime_route_from_metadata(
    route: &SettingRouteId,
    setting_id: &str,
    apply_mode: SettingApplyMode,
) -> SettingsResult<AppRuntimeRoute> {
    match (route.as_str(), apply_mode) {
        (UI_ROUTE_ID, _) => Ok(AppRuntimeRoute::Ui),
        (RENDER_PREVIEW_ROUTE_ID, SettingApplyMode::ImmediatePreview) => {
            Ok(AppRuntimeRoute::RenderPreview)
        }
        (RENDER_COMMITTED_ROUTE_ID, SettingApplyMode::CommittedApply) => {
            Ok(AppRuntimeRoute::RenderCommitted)
        }
        (PLAYER_ROUTE_ID | AUDIO_ROUTE_ID | VIDEO_ROUTE_ID, _) => Ok(AppRuntimeRoute::Player),
        (NETWORK_ROUTE_ID | YOUTUBE_ROUTE_ID, _) => Ok(AppRuntimeRoute::MediaService),
        (other, _) => Err(SettingsError::access_failed(format!(
            "unknown AppConfig settings route `{other}` for setting `{setting_id}`"
        ))),
    }
}

fn route_id_for_runtime_route(route: AppRuntimeRoute) -> SettingRouteId {
    match route {
        AppRuntimeRoute::Ui => SettingRouteId::from(UI_ROUTE_ID),
        AppRuntimeRoute::RenderPreview => SettingRouteId::from(RENDER_PREVIEW_ROUTE_ID),
        AppRuntimeRoute::RenderCommitted => SettingRouteId::from(RENDER_COMMITTED_ROUTE_ID),
        AppRuntimeRoute::Player => SettingRouteId::from(PLAYER_ROUTE_ID),
        AppRuntimeRoute::MediaService => SettingRouteId::from(NETWORK_ROUTE_ID),
    }
}

fn groups_for_settings(
    route: AppRuntimeRoute,
    affected_settings: &[SettingId],
) -> Vec<AppRuntimeRouteGroupUpdate> {
    let mut groups: BTreeMap<AppRuntimeRouteGroup, Vec<SettingId>> = BTreeMap::new();
    for setting_id in affected_settings {
        groups
            .entry(group_for_setting(route, setting_id.as_str()))
            .or_default()
            .push(setting_id.clone());
    }

    groups
        .into_iter()
        .map(|(group, affected_settings)| AppRuntimeRouteGroupUpdate {
            group,
            affected_settings,
        })
        .collect()
}

fn group_for_setting(route: AppRuntimeRoute, setting_id: &str) -> AppRuntimeRouteGroup {
    match route {
        AppRuntimeRoute::Ui if setting_id.starts_with("ui.settings.") => {
            AppRuntimeRouteGroup::UiSettingsRuntime
        }
        AppRuntimeRoute::Ui => AppRuntimeRouteGroup::UiShell,
        AppRuntimeRoute::RenderPreview if setting_id.starts_with("render.hdr_to_sdr.") => {
            AppRuntimeRouteGroup::RenderHdrToSdr
        }
        AppRuntimeRoute::RenderPreview => AppRuntimeRouteGroup::RenderColorAdjustment,
        AppRuntimeRoute::RenderCommitted => AppRuntimeRouteGroup::RenderBackendLifecycle,
        AppRuntimeRoute::Player if setting_id == "audio.volume" => {
            AppRuntimeRouteGroup::PlayerDefaultVolume
        }
        AppRuntimeRoute::Player if setting_id == "audio.output_device" => {
            AppRuntimeRouteGroup::PlayerAudioOutputDevice
        }
        AppRuntimeRoute::Player if player_tick_setting(setting_id) => {
            AppRuntimeRouteGroup::PlayerTickConfig
        }
        AppRuntimeRoute::Player if player_decoder_thread_setting(setting_id) => {
            AppRuntimeRouteGroup::PlayerDecoderThreadConfig
        }
        AppRuntimeRoute::Player if setting_id == "video.preferred_backend" => {
            AppRuntimeRouteGroup::PlayerVideoBackend
        }
        AppRuntimeRoute::Player => AppRuntimeRouteGroup::PlayerDeferredBoundary,
        AppRuntimeRoute::MediaService if setting_id.starts_with("youtube.") => {
            AppRuntimeRouteGroup::MediaYoutube
        }
        AppRuntimeRoute::MediaService => AppRuntimeRouteGroup::MediaNetwork,
    }
}

