/// Full-document validator that delegates to the authoritative config layer.
#[derive(Debug, Clone, Copy, Default)]
pub struct AppConfigValidator;

impl SettingsValidator<AppConfig> for AppConfigValidator {
    fn validate(
        &mut self,
        request: ValidationRequest<'_, AppConfig>,
    ) -> SettingsResult<ValidationReport> {
        request
            .draft
            .validate()
            .map_err(settings_error_from_display)?;

        Ok(ValidationReport::valid(setting_ids_from_diff(
            request.changed_settings,
        )))
    }
}

/// Atomic TOML persister backed by `rustiplayer-config::save_validated_atomic_at`.
#[derive(Debug, Clone)]
pub struct AppConfigStore {
    path: PathBuf,
}

impl AppConfigStore {
    /// Creates a store for one concrete user config path.
    #[must_use]
    pub fn new(path: impl Into<PathBuf>) -> Self {
        Self { path: path.into() }
    }

    /// Returns the target TOML path used by this store.
    #[must_use]
    pub fn path(&self) -> &Path {
        &self.path
    }
}

impl SettingsPersister<AppConfig> for AppConfigStore {
    fn persist(&mut self, request: PersistRequest<'_, AppConfig>) -> SettingsResult<PersistReport> {
        // Важный invariant: этот метод не делает partial write сам; вся durability
        // политика остаётся внутри `rustiplayer-config`.
        save_validated_atomic_at(&self.path, request.document)
            .map_err(settings_error_from_display)?;

        Ok(PersistReport::persisted())
    }
}

/// Combined settings delegate used by future app-level runtime wiring.
pub struct AppConfigSettingsDelegate<A> {
    validator: AppConfigValidator,
    store: AppConfigStore,
    runtime_applier: A,
}

impl<A> AppConfigSettingsDelegate<A> {
    /// Creates a delegate that validates, persists and then calls a runtime applier.
    #[must_use]
    pub fn new(path: impl Into<PathBuf>, runtime_applier: A) -> Self {
        Self {
            validator: AppConfigValidator,
            store: AppConfigStore::new(path),
            runtime_applier,
        }
    }

    /// Returns the concrete config path used by the persistence delegate.
    #[must_use]
    pub fn path(&self) -> &Path {
        self.store.path()
    }

    /// Returns the wrapped runtime applier.
    #[must_use]
    pub fn runtime_applier(&self) -> &A {
        &self.runtime_applier
    }

    /// Returns the wrapped runtime applier mutably.
    #[must_use]
    pub fn runtime_applier_mut(&mut self) -> &mut A {
        &mut self.runtime_applier
    }

    /// Consumes the delegate and returns the wrapped runtime applier.
    #[must_use]
    pub fn into_runtime_applier(self) -> A {
        self.runtime_applier
    }
}

impl<A> SettingsValidator<AppConfig> for AppConfigSettingsDelegate<A> {
    fn validate(
        &mut self,
        request: ValidationRequest<'_, AppConfig>,
    ) -> SettingsResult<ValidationReport> {
        self.validator.validate(request)
    }
}

impl<A> SettingsPersister<AppConfig> for AppConfigSettingsDelegate<A> {
    fn persist(&mut self, request: PersistRequest<'_, AppConfig>) -> SettingsResult<PersistReport> {
        self.store.persist(request)
    }
}

impl<A> CommittedSettingsApplier<AppConfig> for AppConfigSettingsDelegate<A>
where
    A: AppRuntimeRouteApplier,
{
    fn apply_committed(
        &mut self,
        request: CommittedApplyRequest<'_, AppConfig>,
    ) -> SettingsResult<Vec<ApplyRouteReport>> {
        let mut reports = Vec::with_capacity(request.route_updates.len());

        for update in request.route_updates {
            let routes = committed_routes_from_update(
                request.previous_committed,
                request.persisted,
                update,
            )?;
            for route in routes {
                let report = self.runtime_applier.apply_committed_route(route)?;
                reports.push(report.into_core_report());
            }
        }

        Ok(reports)
    }
}

/// Runtime owner route after metadata routes are mapped to project-level owners.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum AppRuntimeRoute {
    /// UI shell/settings-runtime state.
    Ui,

    /// Live render route that may be previewed before persistence.
    RenderPreview,

    /// Committed renderer lifecycle/backend settings.
    RenderCommitted,

    /// Player worker/session/audio-runtime contract route.
    Player,

    /// Network/source/service policy route.
    MediaService,
}

/// Owner-defined atomic group inside a runtime route.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum AppRuntimeRouteGroup {
    /// UI chrome state such as language, skin and telemetry visibility.
    UiShell,

    /// Settings-runtime controls, for example preview pacing.
    UiSettingsRuntime,

    /// Renderer color-adjustment group that can be previewed in-place.
    RenderColorAdjustment,

    /// Renderer HDR-to-SDR group that can be previewed in-place.
    RenderHdrToSdr,

    /// Renderer backend/profile lifecycle settings.
    RenderBackendLifecycle,

    /// Player tick/scheduler settings applied in-place by the worker.
    PlayerTickConfig,

    /// Default-volume policy for future media, not current playback volume.
    PlayerDefaultVolume,

    /// Selected audio output device policy for future audio outputs.
    PlayerAudioOutputDevice,

    /// Decoder/channel/pool settings that require controlled rebuild.
    PlayerDecoderThreadConfig,

    /// Video backend preference applied via app-owned pipeline rebuild.
    PlayerVideoBackend,

    /// Player/audio/video settings without an in-place S07 owner boundary.
    PlayerDeferredBoundary,

    /// Network/source cache and timeout policy.
    MediaNetwork,

    /// YouTube service policy.
    MediaYoutube,
}

