/// Runtime route applier implemented by app-level composition code.
pub trait AppRuntimeRouteApplier {
    /// Applies one typed committed route and returns a detailed route report.
    fn apply_committed_route(
        &mut self,
        route: RuntimeCommittedRoute,
    ) -> SettingsResult<AppRouteApplyReport>;
}

/// Project-specific route result. Technical debt is explicit and never success.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum AppRouteApplyResult {
    /// Route fully applied the update.
    Applied,

    /// Route was already in the requested state.
    Noop,

    /// Previously active preview became committed state.
    PreviewPromoted,

    /// Only part of the route applied.
    PartialFailure { message: String },

    /// Route failed before applying the requested update.
    Failed { message: String },

    /// Route generation conflict blocked apply.
    Conflict {
        /// Generation captured by the editing transaction.
        baseline: RouteGeneration,

        /// Current generation seen before apply.
        current: RouteGeneration,
    },

    /// Honest marker for missing owner boundary; converted to a failed core report.
    DeferredTechnicalDebt { message: String },
}

impl AppRouteApplyResult {
    /// Returns true only for states that mean runtime reached the requested state.
    #[must_use]
    pub const fn is_success(&self) -> bool {
        matches!(self, Self::Applied | Self::Noop | Self::PreviewPromoted)
    }
}

/// Per-group route report for changed/skipped/failed/conflicted settings.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AppRouteGroupReport {
    /// Owner-defined atomic group.
    pub group: AppRuntimeRouteGroup,

    /// Result for this group.
    pub result: AppRouteApplyResult,

    /// Concrete setting ids affected by this group.
    pub affected_settings: Vec<SettingId>,
}

/// Project-specific route report that preserves group-level details.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AppRouteApplyReport {
    /// Typed owner route.
    pub route: AppRuntimeRoute,

    /// Concrete metadata routes that contributed to this owner route.
    pub source_routes: Vec<SettingRouteId>,

    /// Route-level result.
    pub result: AppRouteApplyResult,

    /// Runtime mechanism used by the owner.
    pub mechanism: ApplyMechanism,

    /// Concrete setting ids affected by this route.
    pub affected_settings: Vec<SettingId>,

    /// Owner-defined group details.
    pub groups: Vec<AppRouteGroupReport>,
}

impl AppRouteApplyReport {
    /// Converts to the neutral `settings-core` report expected by the controller.
    #[must_use]
    pub fn into_core_report(self) -> ApplyRouteReport {
        let route_id = self
            .source_routes
            .first()
            .cloned()
            .unwrap_or_else(|| route_id_for_runtime_route(self.route));
        let result = match self.result {
            AppRouteApplyResult::Applied => ApplyRouteResult::Applied,
            AppRouteApplyResult::Noop => ApplyRouteResult::Noop,
            AppRouteApplyResult::PreviewPromoted => ApplyRouteResult::PreviewPromoted,
            AppRouteApplyResult::PartialFailure { message } => {
                ApplyRouteResult::PartialFailure { message }
            }
            AppRouteApplyResult::Failed { message } => ApplyRouteResult::Failed { message },
            AppRouteApplyResult::Conflict { baseline, current } => {
                ApplyRouteResult::Conflict { baseline, current }
            }
            AppRouteApplyResult::DeferredTechnicalDebt { message } => {
                ApplyRouteResult::Failed { message }
            }
        };

        ApplyRouteReport {
            route: route_id,
            result,
            mechanism: self.mechanism,
            affected_settings: self.affected_settings,
        }
    }
}

