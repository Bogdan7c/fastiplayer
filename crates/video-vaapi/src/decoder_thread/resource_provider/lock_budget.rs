//! Короткое ожидание замка пула ресурсов на горячем пути показа (gles2-renderer 12a.2,
//! решение владельца 81).
//!
//! Поиск кадра для показа (`try_resource_*_lookup`) идёт из потока окна и не имеет права
//! надолго блокироваться. Раньше он делал один `try_lock` и при любом пересечении с потоком
//! декодера отвечал `Busy`, а приложение показывало прошлый кадр (повтор, потом пропуск).
//!
//! С тактом показа (`decoder_thread::present_pacing`) декодер просыпается ровно тогда, когда
//! приложение выбирает следующий кадр, и его микросекундные участки под замком (регистрация
//! кадра, учёт запаса, подтверждение возврата) стали совпадать с поиском. Замер 780M:
//! 1–4 ответа `Busy` и 2–3 пропуска кадра за 20 с на 1080p60; с ожиданием ≤ 250 мкс — ноль.
//!
//! Семантика границы не меняется: если замок занят дольше бюджета, ответ по-прежнему `Busy`.

use std::sync::{Mutex, MutexGuard, TryLockError, TryLockResult};
use std::time::{Duration, Instant};

/// Сколько поиск кадра ждёт замок пула, прежде чем ответить `Busy`.
///
/// Участки декодера под замком — единицы микросекунд, поэтому 250 мкс хватает с запасом, а
/// для кадра (16,7 мс на 60 fps) это меньше 2 % бюджета даже в худшем случае.
pub(super) const RESOURCE_LOOKUP_LOCK_BUDGET: Duration = Duration::from_micros(250);

/// Берёт замок, повторяя попытку, пока он занят и бюджет `budget` не исчерпан.
///
/// Между попытками поток уступает процессор (`yield_now`): на двух ядрах T410 держатель
/// замка иначе мог бы не успеть его отпустить. Отравленный замок возвращается сразу.
pub(super) fn lock_within_budget<T>(
    mutex: &Mutex<T>,
    budget: Duration,
) -> TryLockResult<MutexGuard<'_, T>> {
    let started_at = Instant::now();
    loop {
        match mutex.try_lock() {
            Err(TryLockError::WouldBlock) if started_at.elapsed() < budget => {
                std::thread::yield_now();
            }
            outcome => return outcome,
        }
    }
}

