//! Нейтральное описание subtitle дорожки веб-источника.
//!
//! Дескриптор не содержит ссылок на скачивание: подписанные URL хранит только
//! service-owned секретная сторона. Здесь лежат лишь то, что безопасно показать
//! в меню: язык, вид дорожки, название и упорядоченный список форматов.

use super::{
    CandidateDescriptorError, DescriptorTextField, LanguageTag, SubtitleFormatIdentity,
    validate_descriptor_text,
};
use crate::SemanticIdentity;

/// Максимальное число форматов одной дорожки (srv3, vtt и запас на будущее).
pub const MAX_SUBTITLE_FORMATS_PER_TRACK: usize = 8;

/// Максимальная длина названия дорожки в UTF-8 байтах.
const MAX_SUBTITLE_DISPLAY_NAME_UTF8_BYTES: usize = 128;

/// Происхождение субтитров: от этого зависит и меню, и устойчивость загрузки.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum SubtitleKind {
    /// Загруженные автором (ручные) субтитры.
    Manual,
    /// Автоматическое распознавание речи на исходном языке.
    AutoGenerated,
    /// Автоматический перевод распознанной речи на другой язык.
    AutoTranslated,
}

impl SubtitleKind {
    /// Стабильный короткий ключ вида для идентификаторов дорожек.
    #[must_use]
    pub const fn stable_key(self) -> &'static str {
        match self {
            Self::Manual => "manual",
            Self::AutoGenerated => "auto",
            Self::AutoTranslated => "auto-translated",
        }
    }
}

/// Ограниченное человекочитаемое название дорожки, как его дал источник.
#[derive(Clone, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct SubtitleDisplayName(String);

impl SubtitleDisplayName {
    /// Проверяет, что название не пустое и укладывается в байтовый лимит.
    pub fn new(value: impl Into<String>) -> Result<Self, CandidateDescriptorError> {
        let value = value.into();
        validate_descriptor_text(
            &value,
            DescriptorTextField::SubtitleName,
            MAX_SUBTITLE_DISPLAY_NAME_UTF8_BYTES,
        )?;
        Ok(Self(value))
    }

    /// Возвращает название для показа пользователю.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl std::fmt::Debug for SubtitleDisplayName {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter
            .debug_tuple("SubtitleDisplayName")
            .field(&self.0)
            .finish()
    }
}

/// Subtitle дорожка без playback/provider semantics и без ссылок.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct SubtitleDescriptor {
    /// Semantic identity дорожки.
    semantic_identity: SemanticIdentity,
    /// Вид дорожки: ручная, распознанная или переведённая.
    kind: SubtitleKind,
    /// Доступные форматы по убыванию предпочтения (первый пробуют первым).
    formats: Vec<SubtitleFormatIdentity>,
    /// Optional language.
    language: Option<LanguageTag>,
    /// Optional название от источника.
    display_name: Option<SubtitleDisplayName>,
}

impl SubtitleDescriptor {
    /// Создаёт дорожку; форматов должно быть от 1 до `MAX_SUBTITLE_FORMATS_PER_TRACK`.
    pub fn new(
        semantic_identity: SemanticIdentity,
        kind: SubtitleKind,
        formats_by_preference: Vec<SubtitleFormatIdentity>,
    ) -> Result<Self, CandidateDescriptorError> {
        if formats_by_preference.is_empty()
            || formats_by_preference.len() > MAX_SUBTITLE_FORMATS_PER_TRACK
        {
            return Err(CandidateDescriptorError::InvalidSubtitleFormatCount {
                provided: formats_by_preference.len(),
                maximum: MAX_SUBTITLE_FORMATS_PER_TRACK,
            });
        }
        Ok(Self {
            semantic_identity,
            kind,
            formats: formats_by_preference,
            language: None,
            display_name: None,
        })
    }

    /// Добавляет язык дорожки.
    #[must_use]
    pub fn with_language(mut self, language: LanguageTag) -> Self {
        self.language = Some(language);
        self
    }

    /// Добавляет название дорожки от источника.
    #[must_use]
    pub fn with_display_name(mut self, display_name: SubtitleDisplayName) -> Self {
        self.display_name = Some(display_name);
        self
    }

    /// Возвращает semantic identity.
    pub const fn semantic_identity(&self) -> &SemanticIdentity {
        &self.semantic_identity
    }

    /// Возвращает вид дорожки.
    pub const fn kind(&self) -> SubtitleKind {
        self.kind
    }

    /// Возвращает форматы по убыванию предпочтения.
    pub fn formats(&self) -> &[SubtitleFormatIdentity] {
        &self.formats
    }

    /// Возвращает самый предпочтительный формат.
    pub fn preferred_format(&self) -> Option<&SubtitleFormatIdentity> {
        self.formats.first()
    }

    /// Возвращает language.
    pub const fn language(&self) -> Option<&LanguageTag> {
        self.language.as_ref()
    }

    /// Возвращает название дорожки.
    pub const fn display_name(&self) -> Option<&SubtitleDisplayName> {
        self.display_name.as_ref()
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::SourceIdentity;

    fn identity() -> SemanticIdentity {
        SemanticIdentity::new(SourceIdentity::new(1), "sub").expect("identity")
    }

    fn format(name: &str) -> SubtitleFormatIdentity {
        SubtitleFormatIdentity::new(name).expect("format")
    }

    /// Порядок форматов сохраняется: первый остаётся предпочтительным.
    #[test]
    fn formats_keep_preference_order_and_builder_fields() {
        let descriptor = SubtitleDescriptor::new(
            identity(),
            SubtitleKind::AutoTranslated,
            vec![format("srv3"), format("vtt")],
        )
        .expect("descriptor")
        .with_language(LanguageTag::new("ru").expect("lang"))
        .with_display_name(SubtitleDisplayName::new("Russian").expect("name"));
        let formats: Vec<&str> = descriptor
            .formats()
            .iter()
            .map(SubtitleFormatIdentity::as_str)
            .collect();
        assert_eq!(formats, ["srv3", "vtt"]);
        assert_eq!(
            descriptor
                .preferred_format()
                .map(SubtitleFormatIdentity::as_str),
            Some("srv3")
        );
        assert_eq!(descriptor.kind(), SubtitleKind::AutoTranslated);
        assert_eq!(descriptor.language().map(LanguageTag::as_str), Some("ru"));
        assert_eq!(
            descriptor.display_name().map(SubtitleDisplayName::as_str),
            Some("Russian")
        );
    }

    /// Дорожка без форматов и с лишними форматами отвергается.
    #[test]
    fn format_count_is_bounded() {
        let empty = SubtitleDescriptor::new(identity(), SubtitleKind::Manual, Vec::new())
            .expect_err("empty formats");
        assert_eq!(
            empty,
            CandidateDescriptorError::InvalidSubtitleFormatCount {
                provided: 0,
                maximum: MAX_SUBTITLE_FORMATS_PER_TRACK
            }
        );
        let many = (0..=MAX_SUBTITLE_FORMATS_PER_TRACK)
            .map(|index| format(&format!("f{index}")))
            .collect();
        assert!(SubtitleDescriptor::new(identity(), SubtitleKind::Manual, many).is_err());
    }

    /// Пустое и слишком длинное название отвергаются.
    #[test]
    fn display_name_is_bounded() {
        assert!(SubtitleDisplayName::new("").is_err());
        assert!(SubtitleDisplayName::new("я".repeat(100)).is_err());
        assert!(SubtitleDisplayName::new("English").is_ok());
    }
}
