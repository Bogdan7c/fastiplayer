//! Выбор web-субтитров в `track-memory.json`: круговой проход и совместимость схем 1 и 2.

use super::super::*;
use super::{capacity, key_of};
use crate::AtomicWriteOutcome;

fn store_in(directory: &tempfile::TempDir) -> TrackMemoryStore {
    TrackMemoryStore::new(directory.path().join(TRACK_MEMORY_FILENAME))
}

fn web_choice(language: &str, kind: RememberedWebSubtitleKind) -> RememberedSubtitleChoice {
    RememberedSubtitleChoice::Web(
        RememberedWebSubtitle::new(language.to_owned(), kind).expect("valid web choice"),
    )
}

#[test]
fn web_choice_of_every_kind_survives_write_and_inspect_and_file_uses_schema_two() {
    let directory = tempfile::tempdir().expect("dir");
    let store = store_in(&directory);
    let mut memory = TrackMemory::new(capacity(10));
    memory.remember_subtitles(
        key_of("manual"),
        web_choice("en", RememberedWebSubtitleKind::Manual),
    );
    memory.remember_subtitles(
        key_of("asr"),
        web_choice("en", RememberedWebSubtitleKind::AutoGenerated),
    );
    memory.remember_subtitles(
        key_of("translated"),
        web_choice("ru", RememberedWebSubtitleKind::AutoTranslated),
    );

    assert!(matches!(store.write(&memory), AtomicWriteOutcome::Durable));

    let text = std::fs::read_to_string(store.track_memory_path()).expect("file");
    assert!(text.contains(r#""schema_version": 2"#), "{text}");
    // Старый бинарник (схема 1) обязан увидеть «файл новее», а не «повреждён».
    assert_eq!(CURRENT_TRACK_MEMORY_SCHEMA_VERSION, 2);
    let TrackMemoryInspection::Loaded(loaded) = store.inspect(capacity(10)) else {
        panic!("memory must load");
    };
    assert_eq!(
        loaded
            .entry_for(&key_of("translated"))
            .and_then(|entry| entry.subtitles()),
        Some(&web_choice("ru", RememberedWebSubtitleKind::AutoTranslated))
    );
    assert_eq!(
        loaded
            .entry_for(&key_of("asr"))
            .and_then(|entry| entry.subtitles()),
        Some(&web_choice("en", RememberedWebSubtitleKind::AutoGenerated))
    );
    assert_eq!(
        loaded
            .entry_for(&key_of("manual"))
            .and_then(|entry| entry.subtitles()),
        Some(&web_choice("en", RememberedWebSubtitleKind::Manual))
    );
}

#[test]
fn a_file_written_by_the_previous_schema_one_still_loads() {
    let directory = tempfile::tempdir().expect("dir");
    let store = store_in(&directory);
    let fingerprint = key_of("old").to_hex();
    let old_file = format!(
        r#"{{"schema_version":1,"entries":[{{"video_fingerprint_sha256":"{fingerprint}","last_used":1,"subtitles":{{"kind":"off"}},"subtitle_sync_offset_ms":250}}]}}"#
    );
    std::fs::write(store.track_memory_path(), old_file).expect("fixture");

    let TrackMemoryInspection::Loaded(loaded) = store.inspect(capacity(10)) else {
        panic!("a schema 1 file must load");
    };
    let entry = loaded.entry_for(&key_of("old")).expect("entry");
    assert_eq!(entry.subtitles(), Some(&RememberedSubtitleChoice::Off));
    assert_eq!(entry.subtitle_sync_offset().millis(), 250);
}

#[test]
fn a_web_choice_inside_a_schema_one_file_is_rejected_as_corrupt() {
    let directory = tempfile::tempdir().expect("dir");
    let store = store_in(&directory);
    let fingerprint = key_of("v1").to_hex();
    let forged = format!(
        r#"{{"schema_version":1,"entries":[{{"video_fingerprint_sha256":"{fingerprint}","last_used":1,"subtitles":{{"kind":"web","language":"en","track_kind":"manual"}},"subtitle_sync_offset_ms":0}}]}}"#
    );
    std::fs::write(store.track_memory_path(), forged).expect("fixture");

    assert!(matches!(
        store.inspect(capacity(10)),
        TrackMemoryInspection::CorruptNeedsQuarantine {
            cause: TrackMemoryCorruptCause::InvalidV1Payload,
            ..
        }
    ));
}

#[test]
fn web_choice_with_empty_or_overlong_language_is_rejected() {
    assert_eq!(
        RememberedWebSubtitle::new(String::new(), RememberedWebSubtitleKind::Manual),
        Err(RememberedWebSubtitleError::EmptyLanguage)
    );
    assert_eq!(
        RememberedWebSubtitle::new(
            "x".repeat(MAX_HINT_LANGUAGE_BYTES + 1),
            RememberedWebSubtitleKind::Manual
        ),
        Err(RememberedWebSubtitleError::LanguageTooLong)
    );
}

#[test]
fn unknown_web_track_kind_in_a_schema_two_file_is_corrupt() {
    let directory = tempfile::tempdir().expect("dir");
    let store = store_in(&directory);
    let fingerprint = key_of("v2").to_hex();
    let bad = format!(
        r#"{{"schema_version":2,"entries":[{{"video_fingerprint_sha256":"{fingerprint}","last_used":1,"subtitles":{{"kind":"web","language":"en","track_kind":"bogus"}},"subtitle_sync_offset_ms":0}}]}}"#
    );
    std::fs::write(store.track_memory_path(), bad).expect("fixture");

    assert!(matches!(
        store.inspect(capacity(10)),
        TrackMemoryInspection::CorruptNeedsQuarantine { .. }
    ));
}
