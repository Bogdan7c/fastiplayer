//! Запомненный выбор web-субтитров (YouTube и другие extractor-ы).
//!
//! Web-дорожка не имеет ни номера потока, ни файла: её стабильно описывают язык и вид
//! (ручная / распознанная речь / автоперевод). Ссылки на такие дорожки подписаны и живут
//! несколько часов, поэтому в память они не попадают никогда: хранится только это описание,
//! а по нему при следующем открытии находится дорожка в свежем списке видео.
//!
//! Модуль не зависит от `web-media-core`: вид и язык переводит приложение на своей границе.

use std::fmt;

use super::hint::MAX_HINT_LANGUAGE_BYTES;

/// Вид web-дорожки субтитров.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RememberedWebSubtitleKind {
    /// Субтитры, загруженные автором.
    Manual,
    /// Автоматически распознанная речь.
    AutoGenerated,
    /// Автоматический перевод.
    AutoTranslated,
}

/// Почему язык web-дорожки нельзя запомнить.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RememberedWebSubtitleError {
    /// Пустой языковой тег: по такому описанию дорожку не найти.
    EmptyLanguage,
    /// Языковой тег длиннее [`MAX_HINT_LANGUAGE_BYTES`].
    LanguageTooLong,
}

impl fmt::Display for RememberedWebSubtitleError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(match self {
            Self::EmptyLanguage => "remembered web subtitle language is empty",
            Self::LanguageTooLong => "remembered web subtitle language is too long",
        })
    }
}

impl std::error::Error for RememberedWebSubtitleError {}

/// Описание web-дорожки: язык и вид.
///
/// Инвариант: язык непустой и не длиннее [`MAX_HINT_LANGUAGE_BYTES`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RememberedWebSubtitle {
    language: String,
    kind: RememberedWebSubtitleKind,
}

impl RememberedWebSubtitle {
    /// Проверяет язык и строит описание.
    pub fn new(
        language: String,
        kind: RememberedWebSubtitleKind,
    ) -> Result<Self, RememberedWebSubtitleError> {
        if language.is_empty() {
            return Err(RememberedWebSubtitleError::EmptyLanguage);
        }
        if language.len() > MAX_HINT_LANGUAGE_BYTES {
            return Err(RememberedWebSubtitleError::LanguageTooLong);
        }
        Ok(Self { language, kind })
    }

    /// Языковой тег (для автоперевода — целевой язык).
    #[must_use]
    pub fn language(&self) -> &str {
        &self.language
    }

    /// Вид дорожки.
    #[must_use]
    pub const fn kind(&self) -> RememberedWebSubtitleKind {
        self.kind
    }
}
