//! Окно преобразования AC-3 (A/52:2012 §7.9.4, Таблица 7.33; ETSI TS 102 366
//! v1.4.1 Таблица 6.33 — значения совпадают поэлементно).
//!
//! Таблица 7.33 даёт 256 значений половины симметричного 512-точечного окна
//! с точностью 5 знаков. Этой точности мало для сверки с эталоном на уровне
//! ≥ 90 дБ, поэтому окно вычисляется по его математической форме:
//! окно Кайзера–Бесселя производное (KBD) с параметром α = 5,
//!
//! `w[n] = sqrt( Σ_{j=0..n} K[j] / Σ_{j=0..256} K[j] )`, n = 0…255,
//! `K[j] = I0(π·α·sqrt(1 − (2j/256 − 1)²))`,
//!
//! где I0 — модифицированная функция Бесселя первого рода нулевого порядка.
//! Спецификация называет только таблицу, поэтому тесты доказывают, что эта
//! формула и есть Таблица 7.33: все 256 значений совпадают с округлением до
//! 5 знаков, а свойство Принсена–Брэдли `w[n]² + w[255−n]² = 1` (условие
//! точного восстановления TDAC) выполняется с точностью f64.

/// Длина половины окна = число значений Таблицы 7.33.
pub(crate) const HALF_WINDOW_LENGTH: usize = 256;

/// Параметр α окна KBD, при котором формула воспроизводит Таблицу 7.33.
const KBD_ALPHA: f64 = 5.0;

/// Относительная точность, до которой суммируется ряд I0.
const BESSEL_SERIES_TOLERANCE: f64 = 1e-18;
/// Предел числа членов ряда I0 (для аргумента ≤ 5π хватает ~40).
const BESSEL_SERIES_MAX_TERMS: u32 = 200;

/// `I0(x) = Σ_k ((x/2)^k / k!)²` — ряд сходится для любого x.
fn bessel_i0(argument: f64) -> f64 {
    let half = argument / 2.0;
    let mut term = 1.0;
    let mut sum = 1.0;
    for k in 1..=BESSEL_SERIES_MAX_TERMS {
        let factor = half / f64::from(k);
        term *= factor * factor;
        sum += term;
        if term <= sum * BESSEL_SERIES_TOLERANCE {
            break;
        }
    }
    sum
}

/// Половина окна KBD α = 5 в f64 (значения `w[0..256]` Таблицы 7.33).
pub(crate) fn kbd_half_window() -> [f64; HALF_WINDOW_LENGTH] {
    let length = HALF_WINDOW_LENGTH as f64;
    let kaiser = |index: usize| {
        let position = 2.0 * index as f64 / length - 1.0;
        bessel_i0(std::f64::consts::PI * KBD_ALPHA * (1.0 - position * position).sqrt())
    };
    let total: f64 = (0..=HALF_WINDOW_LENGTH).map(kaiser).sum();
    let mut window = [0.0; HALF_WINDOW_LENGTH];
    let mut running = 0.0;
    for (index, value) in window.iter_mut().enumerate() {
        running += kaiser(index);
        *value = (running / total).sqrt();
    }
    window
}

