//! Клипы `\clip` / `\iclip` как стадия «после кэша реплик».
//!
//! ## Зачем отдельная стадия
//! Решение владельца: клипы (и караоке) накладываются ПОСЛЕ кэша реплик, как в libass, и
//! не входят в ключ кэша ([`crate::renderer`]`::CueCacheKey`). Кэш хранит картинки реплики без
//! обрезки; клип — отдельная небольшая геометрия ([`CueClip`]), живущая рядом в записи кэша.
//! Благодаря этому изменение клипа во времени (`\t(\clip(...))`) и заливка караоке не
//! требуют перерисовки текста.
//!
//! ## Кто чем владеет
//! - `ass::clip_plan` знает про сценарий (PlayRes, масштаб кадра, `explicit`) и превращает
//!   `\clip`/`\iclip` реплики в экранные величины: [`ScreenRectClip`] и [`VectorClipPlan`].
//! - [`build_vector_clip_mask`] растеризует фигуру векторного клипа ОДИН раз при рисовании
//!   реплики (и поэтому кэшируется вместе с ней).
//! - [`CueClip::apply`] накладывает клип на картинки при сборке кадра
//!   (`renderer::ass_frame`), ДО сдвига столкновений: libass режет картинки в их
//!   исходном положении, а затем `shift_event` двигает уже обрезанное.
//!
//! ## Анимированный прямоугольник `\t(\clip(...))` (этап 10b, готово)
//! У реплики, где есть `\t` с прямоугольным клипом, в записи кэша лежит не только готовый
//! [`CueClip`] «на момент рисования», но и [`crate::ass::ClipAnimation`] — урезанная копия
//! тегов (только `\clip`/`\iclip` и `\t`), масштаб кадра и признак «явная реплика». При
//! сборке кадра (`RasterizedCue::final_bitmaps`) растеризатор по часам кадра заново проходит
//! эти теги по тем же правилам, что и полный разбор (`ClipAnimation::rect_at`), и подаёт
//! полученный прямоугольник в [`CueClip::apply_with_rect`]. Поэтому:
//! - текст реплики НЕ рисуется заново: ключ кэша (`AssAnimationKey`) вес `\t`, который двигает
//!   только клип, не содержит; реплика с одним таким `\t` рисуется один раз за всю жизнь;
//! - смешанный `\t(\fs70\clip(...))` кладёт в ключ вес (он нужен размеру букв), а клип всё
//!   равно считается здесь, по часам кадра, — одним и тем же кодом;
//! - срок годности картинки честный: любой `\t` с анимацией даёт `AnimationChange::EveryFrame`
//!   внутри `[t1, t2)` и `At(t1 + 1 мс)` до начала (`ass::transform_scan`), поэтому рисовальщик
//!   в фоне не «залипает» на старом кадре;
//! - результат стадии для такого клипа НЕ запоминается (`OnceLock` только для неизменного
//!   клипа): прямоугольник каждый кадр свой, а векторная маска и картинки текста общие.
//!
//! Векторный клип (`\clip(m ...)`) не анимируется: его маска строится один раз при рисовании.
//!
//! ## Караоке (этап 10b, готово)
//! Караоке (`\k`, `\kf`, `\ko`) решает только раскраску картинки ([`ImagePaint`]: цвет, разрез по
//! вертикали `brk`, скрытие), расчёт ведёт [`crate::karaoke`]. Разрез живёт в этой стадии, потому
//! что `render_glyph` libass режет видимый кусок по `brk` внутри того же шага, что и клип: от этого
//! зависит порядок картинок (для инверсного клипа «кусок 1 слева, кусок 1 справа, кусок 2 ...»).
//! Заливка караоке меняется каждый кадр, поэтому результат стадии для такой реплики не запоминается.
//!
//! Пока клип не зависит от времени (нет покадровой анимации), результат стадии запоминается в записи кэша
//! (`RasterizedCue::final_bitmaps`), чтобы картинки клипнутой реплики сохраняли общие маски
//! между кадрами и детектор изменений видел `Unchanged`/`Moved`, а не `Replaced`.

