//! Клипы `\clip` / `\iclip` как стадия «после кэша реплик».
//!
//! ## Зачем отдельная стадия
//! Решение владельца: клипы (и в 10b караоке) накладываются ПОСЛЕ кэша реплик, как в libass, и
//! не входят в ключ кэша ([`crate::renderer`]`::CueCacheKey`). Кэш хранит картинки реплики без
//! обрезки; клип — отдельная небольшая геометрия ([`CueClip`]), живущая рядом в записи кэша.
//! Благодаря этому изменение клипа во времени (`\t(\clip(...))`, 10b) и заливка караоке не
//! требуют перерисовки текста.
//!
//! ## Кто чем владеет
//! - `ass::clip_plan` знает про сценарий (PlayRes, масштаб кадра, `explicit`) и превращает
//!   `\clip`/`\iclip` реплики в экранные величины: [`ScreenRectClip`] и [`VectorClipPlan`].
//! - [`build_vector_clip_mask`] растеризует фигуру векторного клипа ОДИН раз при рисовании
//!   реплики (и поэтому кэшируется вместе с ней).
//! - [`CueClip::apply`] накладывает клип на картинки при сборке кадра
//!   (`renderer::ass_frame`), ДО сдвига столкновений: libass режет картинки в их
//!   исходном положении, а затем `shift_event` двигает уже обрезанное.
//!
//! ## Как сюда встроится 10b
//! - Анимированный прямоугольник `\t(\clip(...))`: у реплики хранится не готовый
//!   [`ScreenRectClip`], а его описание (углы начала/конца и время `\t`); при сборке кадра оно
//!   вычисляется на момент кадра и подаётся в тот же [`CueClip::apply`]. Ключ кэша не меняется.
//! - Караоке (`\k`, `\kf`, `\ko`): разделение картинки по `brk` и выбор цвета — ещё один
//!   шаг этой же стадии (у `render_glyph` libass он выполняется вместе с клипом), поэтому
//!   `push_visible_parts` в 10b получит параметр разреза.
//!
//! Пока клип не зависит от времени, результат стадии запоминается в записи кэша
//! (`RasterizedCue::final_bitmaps`), чтобы картинки клипнутой реплики сохраняли общие маски
//! между кадрами и детектор изменений видел `Unchanged`/`Moved`, а не `Replaced`.

