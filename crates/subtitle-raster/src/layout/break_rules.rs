//! Правила разрешённых мест автоматического переноса строки.
//!
//! Оригинальная реализация проекта (не порт libass): libass без `libunibreak` переносит только
//! после пробела, и эту часть мы сохраняем побитово для ASS ([`BreakOpportunities::SpacesOnly`]).
//! Для простых форматов ([`BreakOpportunities::SpacesAndCjk`]) добавлены разрывы рядом с
//! китайскими, японскими и корейскими символами — упрощённый вариант класса `ID` из UAX #14:
//!
//! * разрыв разрешён между двумя CJK-символами и на границе CJK-символа с любым не-пробельным
//!   символом (например, «2020年» или «ABC你好»);
//! * кинсоку: нельзя переносить ПЕРЕД закрывающей пунктуацией, малой каной, знаком долготы
//!   `ー`, знаками повтора и точками, и нельзя оставлять открывающую скобку в конце строки;
//! * нельзя отрывать от основы комбинирующие знаки, селекторы начертаний и ZWJ, нельзя
//!   разрывать кластер, поглощённый лигатурой (`skip`), а также неразрывные пробелы;
//! * разрыв допустим только внутри одного уровня BiDi, иначе порядок отображения строк
//!   перестал бы совпадать с логическим.
//!
//! Модуль чистый: смотрит только на пару соседних кластеров и политику.

use crate::event_style::BreakOpportunities;
use crate::glyph_info::TextCluster;

/// Можно ли начать новую строку сразу ПОСЛЕ кластера `current`, если следом идёт `next`
/// (`None` — текст закончился, переносить нечего).
pub(super) fn allows_break_between(
    current: &TextCluster,
    next: Option<&TextCluster>,
    policy: BreakOpportunities,
) -> bool {
    // Пробел — единственное место разрыва у libass; в режиме CJK это правило остаётся прежним.
    if current.symbol == ' ' {
        return true;
    }
    match policy {
        BreakOpportunities::SpacesOnly => false,
        BreakOpportunities::SpacesAndCjk => {
            next.is_some_and(|next| allows_cjk_break(current, next))
        }
    }
}

/// Разрыв между `current` и `next` по правилам CJK (пробелы уже разобраны вызывающим).
fn allows_cjk_break(current: &TextCluster, next: &TextCluster) -> bool {
    let (before, after) = (current.symbol, next.symbol);
    // Явный перевод строки и пробел справа от разрыва переносом CJK не обслуживаются:
    // пробел сам станет местом разрыва, `\n` — принудительный разрыв.
    if matches!(after, ' ' | '\n') || before == '\n' {
        return false;
    }
    if !is_cjk_break_candidate(before) && !is_cjk_break_candidate(after) {
        return false;
    }
    // Рисунки `\p` — не текст; кластер, поглощённый лигатурой, нельзя оторвать от её начала.
    if current.drawing.is_some() || next.drawing.is_some() || next.skip {
        return false;
    }
    if current.bidi_level != next.bidi_level {
        return false;
    }
    !forbids_break_after(before) && !forbids_break_before(after)
}

/// Символ, рядом с которым действуют разрывы в стиле `ID` (иероглифы, кана, хангыль, CJK- и
/// полноширинная пунктуация).
fn is_cjk_break_candidate(symbol: char) -> bool {
    matches!(
        u32::from(symbol),
        0x3000..=0x303F // CJK-символы и пунктуация
        | 0x3040..=0x309F // хирагана
        | 0x30A0..=0x30FF // катакана
        | 0x31F0..=0x31FF // фонетические расширения катаканы
        | 0x3400..=0x4DBF // иероглифы, расширение A
        | 0x4E00..=0x9FFF // унифицированные иероглифы
        | 0xAC00..=0xD7AF // слоги хангыля
        | 0xF900..=0xFAFF // совместимые иероглифы
        | 0xFE30..=0xFE4F // совместимые CJK-формы
        | 0xFF00..=0xFFEF // полу- и полноширинные формы (включая полуширинную катакану)
        | 0x20000..=0x2FFFF // иероглифы, дополнительные плоскости
    )
}

/// Символ, перед которым переносить нельзя (кинсоку и «присоединяемые» знаки).
fn forbids_break_before(symbol: char) -> bool {
    is_attached_mark(symbol)
        || is_non_breaking_space(symbol)
        || matches!(
            symbol,
            // Закрывающая и разделяющая пунктуация: CJK, полноширинная и ASCII.
            '、' | '。' | '，' | '．' | '：' | '；' | '！' | '？' | '）' | '］' | '｝' | '〕'
                | '〉' | '》' | '」' | '』' | '】' | '〙' | '〗' | '〞' | '〟' | '’' | '”'
                | ')' | ']' | '}' | '!' | '?' | ',' | '.' | ':' | ';'
                // Точки, многоточие, идеографический пробел.
                | '・' | '･' | '…' | '‥' | '\u{3000}'
                // Знаки долготы и повтора.
                | 'ー' | 'ｰ' | '々' | 'ゝ' | 'ゞ' | 'ヽ' | 'ヾ'
                // Полуширинные знаки звонкости.
                | '\u{FF9E}' | '\u{FF9F}'
                // Малая хирагана и катакана.
                | 'ぁ' | 'ぃ' | 'ぅ' | 'ぇ' | 'ぉ' | 'っ' | 'ゃ' | 'ゅ' | 'ょ' | 'ゎ' | 'ゕ' | 'ゖ'
                | 'ァ' | 'ィ' | 'ゥ' | 'ェ' | 'ォ' | 'ッ' | 'ャ' | 'ュ' | 'ョ' | 'ヮ' | 'ヵ' | 'ヶ'
        )
}

/// Символ, после которого переносить нельзя (открывающие скобки, «склеивающие» знаки).
fn forbids_break_after(symbol: char) -> bool {
    is_non_breaking_space(symbol)
        || symbol == '\u{200D}' // ZWJ склеивает с последующим символом
        || matches!(
            symbol,
            '（' | '［' | '｛' | '〔' | '〈' | '《' | '「' | '『' | '【' | '〘' | '〖' | '〝'
                | '‘' | '“' | '(' | '[' | '{'
        )
}

/// Комбинирующие знаки, селекторы начертаний и ZWJ: часть предыдущего символа.
fn is_attached_mark(symbol: char) -> bool {
    matches!(
        u32::from(symbol),
        0x0300..=0x036F
        | 0x1AB0..=0x1AFF
        | 0x1DC0..=0x1DFF
        | 0x20D0..=0x20FF
        | 0xFE20..=0xFE2F
        | 0x3099..=0x309A // комбинирующие дакутэн и хандакутэн
        | 0xFE00..=0xFE0F // селекторы начертаний
        | 0xE0100..=0xE01EF // дополнительные селекторы начертаний
        | 0x200D // ZWJ
    )
}

/// Неразрывные пробелы и «словесный соединитель»: переносить рядом с ними нельзя.
fn is_non_breaking_space(symbol: char) -> bool {
    matches!(symbol, '\u{00A0}' | '\u{202F}' | '\u{2060}' | '\u{FEFF}')
}

