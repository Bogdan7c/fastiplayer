//! Тесты разбора субтитров: на входе JSON как у yt-dlp, на выходе дорожки.

use std::time::{Duration, UNIX_EPOCH};

use serde_json::{Value, json};
use web_media_core::{ExtractionGeneration, LanguageTag, SourceIdentity, SubtitleKind};

use super::{YtDlpSubtitleFormat, YtDlpSubtitleInventory};
use crate::candidate::normalize::normalize_candidate_document;
use crate::candidate::raw::YtDlpCandidateDocument;

/// Подписанная ссылка в стиле YouTube; в ней есть слова-маркеры секрета.
fn link(extra_query: &str) -> String {
    format!(
        "https://example.invalid/api/timedtext?v=abc&expire=2000000000{extra_query}&signature=SECRET"
    )
}

fn entry(ext: &str, name: &str, extra_query: &str) -> Value {
    json!({"ext": ext, "url": link(extra_query), "name": name})
}

/// Прогоняет JSON через тот же DTO и нормализатор, что production.
fn inventory_of(payload: Value) -> YtDlpSubtitleInventory {
    let document: YtDlpCandidateDocument =
        serde_json::from_value(payload).expect("synthetic JSON must deserialize");
    normalize_candidate_document(
        document,
        SourceIdentity::new(7),
        ExtractionGeneration::new(1),
    )
    .subtitle_inventory()
    .clone()
}

fn language(tag: &str) -> LanguageTag {
    LanguageTag::new(tag).expect("language")
}

fn format_names(track: &super::YtDlpSubtitleTrack) -> Vec<&str> {
    track
        .descriptor()
        .formats()
        .iter()
        .map(|format| format.as_str())
        .collect()
}

/// Ручные, распознанные и переведённые дорожки различаются по карте и `tlang`.
#[test]
fn kinds_languages_names_and_format_order_are_normalized() {
    let inventory = inventory_of(json!({
        "subtitles": {
            "ru": [entry("vtt", "Russian", ""), entry("json3", "Russian", ""), entry("srv3", "Russian", "")],
            "de": [entry("ttml", "German", "")]
        },
        "automatic_captions": {
            "en": [entry("vtt", "English", "&kind=asr"), entry("srv3", "English", "&kind=asr")],
            "fr": [entry("srv3", "French", "&kind=asr&lang=en&tlang=fr")]
        }
    }));

    let kinds: Vec<_> = inventory
        .tracks()
        .iter()
        .map(|track| (track.kind(), track.language().map(LanguageTag::as_str)))
        .collect();
    // "de" содержит только ttml и потому выпадает; порядок: ручные, ASR, перевод.
    assert_eq!(
        kinds,
        [
            (SubtitleKind::Manual, Some("ru")),
            (SubtitleKind::AutoGenerated, Some("en")),
            (SubtitleKind::AutoTranslated, Some("fr")),
        ]
    );
    let russian = &inventory.tracks()[0];
    assert_eq!(
        format_names(russian),
        ["srv3", "vtt"],
        "srv3 first, other formats dropped"
    );
    assert_eq!(russian.sources()[0].format(), YtDlpSubtitleFormat::Srv3);
    assert_eq!(russian.sources()[1].format(), YtDlpSubtitleFormat::WebVtt);
    assert_eq!(
        russian
            .descriptor()
            .display_name()
            .map(|name| name.as_str()),
        Some("Russian")
    );
    assert_eq!(
        russian.sources()[0].expires_at(),
        Some(UNIX_EPOCH + Duration::from_secs(2_000_000_000))
    );
}

/// `en-orig` и `en` (обе ASR) дают одну дорожку, а не две.
#[test]
fn original_asr_key_is_deduplicated_with_plain_key() {
    let inventory = inventory_of(json!({
        "automatic_captions": {
            "en-orig": [entry("srv3", "English (Original)", "&kind=asr")],
            "en": [entry("vtt", "English", "&kind=asr")]
        }
    }));
    assert_eq!(inventory.tracks().len(), 1);
    let track = &inventory.tracks()[0];
    assert_eq!(track.kind(), SubtitleKind::AutoGenerated);
    assert_eq!(track.language(), Some(&language("en")));
    assert_eq!(
        format_names(track),
        ["srv3", "vtt"],
        "formats of both keys are merged"
    );
    assert_eq!(
        track.descriptor().display_name().map(|name| name.as_str()),
        Some("English"),
        "plain key name wins over the -orig name"
    );
}

/// Чат прямой трансляции не попадает в субтитры.
#[test]
fn live_chat_is_filtered_out() {
    let inventory = inventory_of(json!({
        "subtitles": {"live_chat": [{"ext": "json", "protocol": "youtube_live_chat", "url": link("")}]}
    }));
    assert!(inventory.tracks().is_empty());
    // Даже под обычным языком и подходящим расширением чат по протоколу отбрасывается.
    let inventory = inventory_of(json!({
        "subtitles": {"en": [{"ext": "vtt", "protocol": "youtube_live_chat", "url": link("")}]}
    }));
    assert!(inventory.tracks().is_empty());
}

/// Кривые записи пропускаются, а валидная дорожка и весь кандидат выживают.
#[test]
fn malformed_entries_are_skipped_without_failing_candidate() {
    let inventory = inventory_of(json!({
        "title": "still parsed",
        "subtitles": {
            "en": [42, {"ext": 5, "url": "x"}, {"ext": "srv3"}, {"ext": "srv3", "url": "not a url"},
                   {"ext": "vtt", "url": "ftp://example.invalid/x"}, entry("vtt", "English", "")],
            "xx": "not an array",
            "": [entry("vtt", "Empty language", "")]
        },
        "automatic_captions": ["not", "a", "map"]
    }));
    assert_eq!(inventory.tracks().len(), 1);
    assert_eq!(format_names(&inventory.tracks()[0]), ["vtt"]);

    // Корень субтитров неправильного типа не ломает десериализацию документа.
    assert!(
        inventory_of(json!({"subtitles": 5, "automatic_captions": "x"}))
            .tracks()
            .is_empty()
    );
}

/// Без субтитров список пуст.
#[test]
fn absent_subtitles_give_empty_inventory() {
    let inventory = inventory_of(json!({"title": "x"}));
    assert!(inventory.tracks().is_empty());
    assert_eq!(inventory.omitted_track_count(), 0);
}

/// Лимит оставляет ручные и ASR, режет переводы и считает отброшенное.
#[test]
fn track_limit_keeps_manual_and_asr_before_translations() {
    let mut translations = serde_json::Map::new();
    for index in 0..300 {
        translations.insert(
            format!("t{index:03}"),
            json!([entry(
                "vtt",
                "T",
                &format!("&kind=asr&lang=en&tlang=t{index:03}")
            )]),
        );
    }
    translations.insert("en".into(), json!([entry("vtt", "English", "&kind=asr")]));
    let inventory = inventory_of(json!({
        "subtitles": {"ru": [entry("vtt", "Russian", "")]},
        "automatic_captions": Value::Object(translations)
    }));
    assert_eq!(
        inventory.tracks().len(),
        web_media_core::MAX_SUBTITLE_DESCRIPTORS
    );
    assert_eq!(
        inventory.omitted_track_count(),
        302 - web_media_core::MAX_SUBTITLE_DESCRIPTORS
    );
    assert_eq!(inventory.tracks()[0].kind(), SubtitleKind::Manual);
    assert_eq!(inventory.tracks()[1].kind(), SubtitleKind::AutoGenerated);
}

/// Отладочный вывод не содержит ни подписи, ни пути, ни query.
#[test]
fn debug_output_never_contains_signed_link_material() {
    let inventory = inventory_of(json!({
        "subtitles": {"en": [entry("srv3", "English", "")]}
    }));
    let rendered = format!("{inventory:?} {:?}", inventory.tracks()[0].sources());
    for forbidden in ["SECRET", "signature", "timedtext", "expire", "abc"] {
        assert!(
            !rendered.contains(forbidden),
            "leaked {forbidden}: {rendered}"
        );
    }
}

/// `find_track` ищет по смыслу и различает вид.
#[test]
fn find_track_matches_by_kind_and_language() {
    let inventory = inventory_of(json!({
        "subtitles": {"en": [entry("vtt", "English", "")]},
        "automatic_captions": {"en": [entry("vtt", "English", "&kind=asr")]}
    }));
    assert!(
        inventory
            .find_track(SubtitleKind::Manual, &language("en"))
            .is_some()
    );
    assert!(
        inventory
            .find_track(SubtitleKind::AutoGenerated, &language("en"))
            .is_some()
    );
    assert!(
        inventory
            .find_track(SubtitleKind::AutoTranslated, &language("en"))
            .is_none()
    );
    assert!(
        inventory
            .find_track(SubtitleKind::Manual, &language("ru"))
            .is_none()
    );
}

/// HLS-плейлисты субтитров (`m3u8_native`) не считаются дорожками, даже с `ext=vtt`.
#[test]
fn hls_playlist_entries_are_not_subtitle_files() {
    let inventory = inventory_of(json!({
        "automatic_captions": {
            "en": [{"ext": "vtt", "protocol": "m3u8_native", "url": "https://example.invalid/api/manifest/index.m3u8?signature=SECRET"}]
        }
    }));
    assert!(inventory.tracks().is_empty());
}
