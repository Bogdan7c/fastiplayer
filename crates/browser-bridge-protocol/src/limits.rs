//! Лимиты протокола моста.
//!
//! Это часть договора двух программ (экстеншен ↔ плеер), а не настройка
//! пользователя: обе стороны обязаны знать одни и те же числа, иначе одна
//! отправит то, что другая честно отвергнет. Поэтому они живут здесь как
//! константы версии протокола. Сколько буфера держит плеер (около 2 минут
//! вперёд, `results/00c.md`), решает уже плеер своими настройками (сессия 03).
//!
//! Меняются лимиты только вместе с версией протокола (`crate::version`).

/// Наибольшее JSON-сообщение (управление и события), байт UTF-8.
///
/// Самое длинное честное сообщение — меню из [`MAX_VARIANT_OPTIONS`] вариантов
/// по [`MAX_VARIANT_LABEL_BYTES`]: 256 × (256 + служебные поля ≈ 60) ≈ 80 КиБ
/// в худшем случае. Реальные меню (24 дорожки звука YouTube) — единицы КиБ.
/// 128 КиБ с запасом покрывают худший случай и всё ещё в 8 раз меньше
/// предела native messaging от хоста к браузеру (1 048 576 байт, `results/00.md`).
pub const MAX_JSON_MESSAGE_BYTES: usize = 128 * 1024;

/// Наибольший полезный груз одной двоичной рамки, байт.
///
/// Крупный `appendBuffer` (Tortuga кладёт 33 МиБ за 10 с) экстеншен режет на
/// рамки сам: плеер собирает байты каждого SourceBuffer подряд, границы кусков
/// для него не важны (YouTube и так режет посреди бокса). 1 МиБ держит память
/// приёмника предсказуемой и совпадает с пределом native messaging.
pub const MAX_DATA_FRAME_PAYLOAD_BYTES: usize = 1024 * 1024;

/// Размер заголовка двоичной рамки, байт (формат — `crate::data_frame`).
pub const DATA_FRAME_HEADER_BYTES: usize = 24;

/// Наибольшее число SourceBuffer в одном поколении.
///
/// На эталоне встречалось 1–2 (`results/00.md`): звук и видео вместе или
/// раздельно. Браузеры сами редко дают больше 3. 8 — запас без риска раздуть
/// таблицы приёмника.
pub const MAX_SOURCE_BUFFERS_PER_GENERATION: u16 = 8;

/// Наибольшая длина заголовка страницы, байт UTF-8.
///
/// Заголовок идёт только в подпись окна. Экстеншен обрезает длинный заголовок
/// по границе символа сам; протокол длиннее не принимает.
pub const MAX_PAGE_TITLE_BYTES: usize = 1024;

/// Наибольшая длина домена страницы, байт (предел имени DNS — 253).
pub const MAX_SITE_DOMAIN_BYTES: usize = 253;

/// Наибольшая длина MIME-типа из `addSourceBuffer`/`changeType`, байт ASCII.
///
/// Самые длинные реальные строки (`video/mp4; codecs="avc1.64002a,mp4a.40.2"`)
/// короче 64 байт; 256 — с запасом на редкие профили.
pub const MAX_MIME_TYPE_BYTES: usize = 256;

/// Наибольшая длина непрозрачного идентификатора (ключ сеанса, ID варианта), байт.
pub const MAX_OPAQUE_ID_BYTES: usize = 64;

/// Наименьшая длина одноразового токена сеанса, байт.
///
/// 32 символа base64url = 192 бита случайности: подобрать за время жизни
/// сеанса нельзя.
pub const MIN_SESSION_TOKEN_BYTES: usize = 32;

/// Наибольшая длина одноразового токена сеанса, байт.
pub const MAX_SESSION_TOKEN_BYTES: usize = 128;

/// Наибольшая длина подписи варианта (озвучка, качество, субтитры), байт UTF-8.
pub const MAX_VARIANT_LABEL_BYTES: usize = 256;

/// Наибольшее число вариантов в одном меню.
///
/// У YouTube бывает 24 дорожки звука (`results/00.md`), у сериалов — десятки
/// озвучек. 256 — с запасом.
pub const MAX_VARIANT_OPTIONS: usize = 256;

/// Наибольшее число меток возможностей в `Hello`.
pub const MAX_CAPABILITY_TOKENS: usize = 64;

/// Наибольшая длина одной метки возможности, байт ASCII.
pub const MAX_CAPABILITY_TOKEN_BYTES: usize = 64;

/// Наибольшая длина строки версии программы (`0.2.0`, `1.4.0-beta.2`), байт ASCII.
pub const MAX_SOFTWARE_VERSION_BYTES: usize = 32;

/// Наибольший запрос байтов файла `<video src>` за один раз, байт.
///
/// Плеер просит файл кусками (`fetch_range`), экстеншен качает их из background
/// с `Range` и отдаёт рамками по [`MAX_DATA_FRAME_PAYLOAD_BYTES`]. 16 МиБ —
/// несколько секунд даже для 4K и не раздувают память экстеншена.
pub const MAX_RANGE_FETCH_BYTES: u64 = 16 * 1024 * 1024;

/// Наибольшее целое, которое JavaScript хранит точно (`Number.MAX_SAFE_INTEGER`).
///
/// Все целые в JSON протокола не больше этого числа: экстеншен на TypeScript
/// читает их как `number`, и большее значение там молча округлится.
pub const MAX_JSON_SAFE_INTEGER: u64 = (1 << 53) - 1;

/// Наименьшая скорость воспроизведения, тысячные доли (0,063×).
///
/// Chromium и Firefox принимают `playbackRate` от 0,0625 до 16.
pub const MIN_PLAYBACK_RATE_PERMILLE: u32 = 63;

/// Наибольшая скорость воспроизведения, тысячные доли (16×).
pub const MAX_PLAYBACK_RATE_PERMILLE: u32 = 16_000;
