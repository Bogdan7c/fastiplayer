//! Нейтральные события жеста перетаскивания.
//!
//! Эти типы не знают про winit: [`super::winit_source`] — единственный файл, который
//! переводит события конкретного источника (патч winit 0.30 или устаревшие
//! `HoveredFile`/`DroppedFile`) в язык этого модуля. Когда выйдет стабильный winit 0.31,
//! менять придётся только переходник; жест, классификатор и маршрутизация останутся.

use super::request::ExternalOpenItem;

/// Позиция курсора в физических пикселях клиентской области окна.
///
/// Физические пиксели — то, что отдаёт источник событий. Пересчёт в точки egui
/// (с учётом масштаба) делает [`super::target`], чтобы ни один другой модуль не
/// путал две системы координат.
#[derive(Clone, Copy, Debug, PartialEq)]
pub(crate) struct PhysicalDropPosition {
    /// Горизонталь, физические пиксели.
    pub(crate) x: f64,
    /// Вертикаль, физические пиксели.
    pub(crate) y: f64,
}

/// Событие одного жеста перетаскивания: вход, движение, бросок или уход.
///
/// Контракт жеста: `Entered`, ноль или более `Moved`, затем ровно один финал —
/// `Dropped` либо `Left`. Приёмник (см. [`super::gesture`]) терпим к нарушениям
/// порядка: потерянный `Entered` не мешает обработать бросок.
#[derive(Clone, Debug, PartialEq)]
pub(crate) enum DropGestureEvent {
    /// Курсор с данными вошёл в окно. Позиции может не быть (устаревший источник).
    Entered {
        /// Позиция входа, если источник её сообщает.
        position: Option<PhysicalDropPosition>,
    },
    /// Курсор переместился над окном.
    Moved {
        /// Новая позиция курсора.
        position: PhysicalDropPosition,
    },
    /// Данные брошены: все элементы жеста уже собраны в исходном порядке.
    Dropped {
        /// Точка броска, если источник её сообщает.
        position: Option<PhysicalDropPosition>,
        /// Содержимое броска в порядке источника.
        items: Vec<ExternalOpenItem>,
    },
    /// Жест закончился без броска (ушёл, отменён, данные не прочитались).
    Left,
}
