//! Web-субтитры до пикселей: выбор дорожки тем же действием, что и меню -> фальшивая загрузка ->
//! разбор srv3 -> владелец -> настоящий рисовальщик -> настоящий GPU-проход -> readback.
//! Тесты пропускаются (с сообщением), если на машине нет GPU adapter-а.

use media_source_open::web_subtitle_fetch::WebSubtitleFetchError;
use web_media_core::SubtitleKind;

use super::ass_gpu_support::*;
use super::gpu_chain::Harness;
use super::track_selection::settle;
use super::web_support::*;
use super::*;

macro_rules! gpu_or_skip {
    () => {
        match Harness::with_size(WINDOW_WIDTH, WINDOW_HEIGHT) {
            Some(harness) => harness,
            None => {
                eprintln!("skip: no GPU adapter for the web subtitle test");
                return;
            }
        }
    };
}

/// Светлый пиксель текста: красный канал «видео» (64) и затемнённой плашки ниже порога.
fn is_light(pixel: [u8; 4]) -> bool {
    pixel[0] > 150
}

fn frame_at(
    owner: &mut SubtitleOwner,
    harness: &mut Harness,
    media: MediaInstanceId,
    pts_millis: u64,
) -> Vec<u8> {
    render_placed(owner, harness, media, full_window_picture(), pts_millis)
}

#[test]
fn selected_web_track_is_downloaded_parsed_and_drawn_at_its_cue_time() {
    let mut harness = gpu_or_skip!();
    let media = instance(1);
    let downloader = FakeWebDownloader::with_replies(vec![srv3_reply(MANUAL_SRV3)]);
    let mut owner = web_owner(
        &SubtitlesConfig::default(),
        media,
        web_source(
            vec![web_track(SubtitleKind::Manual, "en", Some("English"))],
            &downloader,
        ),
    );
    assert_eq!(
        downloader.call_count(),
        0,
        "subtitles are off: nothing is downloaded yet"
    );
    let hidden = frame_at(&mut owner, &mut harness, media, 2_000);
    assert!(
        bounds_of(&hidden, WINDOW_WIDTH, is_light).is_none(),
        "no ink before the user picks a track"
    );

    click_menu_row(&mut owner, "English");
    settle(&mut owner);

    assert_eq!(
        downloader.requested_tracks(),
        [web_track_id(SubtitleKind::Manual, "en")]
    );
    let during_cue = frame_at(&mut owner, &mut harness, media, 2_000);
    let after_cue = frame_at(&mut owner, &mut harness, media, 5_000);
    assert!(
        bounds_of(&during_cue, WINDOW_WIDTH, is_light).is_some(),
        "the downloaded cue is drawn"
    );
    assert!(
        bounds_of(&after_cue, WINDOW_WIDTH, is_light).is_none(),
        "and gone after its end"
    );
}

#[test]
fn speech_recognition_words_appear_one_by_one_on_screen() {
    let mut harness = gpu_or_skip!();
    let media = instance(1);
    let downloader = FakeWebDownloader::with_replies(vec![srv3_reply(ASR_SRV3)]);
    let mut owner = web_owner(
        &enabled_config(),
        media,
        web_source(
            vec![web_track(
                SubtitleKind::AutoGenerated,
                "en",
                Some("English (Original)"),
            )],
            &downloader,
        ),
    );
    assert_eq!(
        owner.lifecycle_view(),
        SubtitleLifecycleView::Ready,
        "auto-selected and loaded"
    );

    let before_reveal = frame_at(&mut owner, &mut harness, media, 1_000);
    let after_reveal = frame_at(&mut owner, &mut harness, media, 3_000);

    let ink_before = count_of(&before_reveal, is_light);
    let ink_after = count_of(&after_reveal, is_light);
    assert!(ink_before > 0, "HELLO is visible");
    assert!(
        ink_after > ink_before * 3 / 2,
        "WORLD adds a lot of ink: {ink_before} -> {ink_after}"
    );
}

#[test]
fn retry_after_rate_limit_ends_with_ink_on_screen() {
    let mut harness = gpu_or_skip!();
    let media = instance(1);
    let downloader = FakeWebDownloader::with_replies(vec![
        FakeReply::Error(WebSubtitleFetchError::RateLimited { retry_after: None }),
        srv3_reply(MANUAL_SRV3),
    ]);
    let mut owner = web_owner(
        &SubtitlesConfig::default(),
        media,
        web_source(
            vec![web_track(
                SubtitleKind::AutoTranslated,
                "ru",
                Some("Russian"),
            )],
            &downloader,
        ),
    );

    click_menu_row(&mut owner, "Russian (auto, translated)");
    settle(&mut owner);
    let failed = frame_at(&mut owner, &mut harness, media, 2_000);
    click_menu_row(&mut owner, "Russian (auto, translated)");
    settle(&mut owner);
    let retried = frame_at(&mut owner, &mut harness, media, 2_000);

    assert!(
        bounds_of(&failed, WINDOW_WIDTH, is_light).is_none(),
        "the video plays without subtitles"
    );
    assert!(
        bounds_of(&retried, WINDOW_WIDTH, is_light).is_some(),
        "the retry draws the cue"
    );
    assert_eq!(downloader.call_count(), 2);
}
