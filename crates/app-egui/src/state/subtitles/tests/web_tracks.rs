fn config_with_languages(enabled: bool, languages: &[&str]) -> SubtitlesConfig {
    SubtitlesConfig {
        enabled,
        preferred_languages: languages.join(","),
        ..SubtitlesConfig::default()
    }
}

/// Строка меню, отмеченная как выбранная (подпись), если есть.
fn selected_row(owner: &SubtitleOwner) -> Option<String> {
    let view = owner.menu_view();
    let index = view.tracks.iter().position(|track| track.is_selected)?;
    menu_texts(owner).get(index).map(|(text, _)| text.clone())
}

fn wait_until(what: &str, mut condition: impl FnMut() -> bool) {
    let deadline = Instant::now() + Duration::from_secs(10);
    while !condition() {
        assert!(Instant::now() < deadline, "timed out waiting for {what}");
        std::thread::sleep(Duration::from_millis(2));
    }
}

