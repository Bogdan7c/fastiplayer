#[test]
fn rate_limited_download_keeps_the_track_clickable_and_retries_only_on_click() {
    let downloader = FakeWebDownloader::with_replies(vec![
        FakeReply::Error(WebSubtitleFetchError::RateLimited { retry_after: None }),
        srv3_reply(MANUAL_SRV3),
    ]);
    let mut owner = web_owner(
        &config_with_languages(false, &[]),
        instance(1),
        web_source(mixed_tracks(), &downloader),
    );
    // Сдвиг и видимость, которые сбой обязан не тронуть.
    owner.apply_control_action(SubtitleControlAction::NudgeSync(SyncNudge::Later));
    let offset_before = owner.menu_view().sync_offset;

    click_menu_row(&mut owner, "Russian (auto, translated)");
    settle(&mut owner);

    assert_eq!(downloader.call_count(), 1);
    assert_eq!(
        take_failures(&mut owner),
        [WebSubtitleFetchError::RateLimited { retry_after: None }],
        "one notice for the failed attempt"
    );
    assert!(
        take_failures(&mut owner).is_empty(),
        "the notice is handed out once"
    );
    assert!(matches!(
        owner.unavailable_failure(),
        Some(SubtitleLoadFailure::DownloadFailed(
            WebSubtitleFetchError::RateLimited { .. }
        ))
    ));
    let view = owner.menu_view();
    let row = view
        .tracks
        .iter()
        .find(|track| track.label.is_auto_translation() && track.is_selected)
        .expect("the failed track stays selected in the menu");
    assert_eq!(
        row.availability,
        SubtitleTrackAvailability::Available,
        "the track stays enabled so a click can retry"
    );
    assert_eq!(view.visibility, SubtitleVisibility::Shown);
    assert_eq!(view.sync_offset, offset_before, "the delay is untouched");
    assert!(
        owner
            .media
            .as_ref()
            .expect("media")
            .tracks
            .entries()
            .iter()
            .filter(|entry| !matches!(entry.load, TrackLoadState::Unavailable(_)))
            .all(|entry| matches!(entry.load, TrackLoadState::NotLoaded)),
        "other tracks were not touched"
    );

    // Без клика повторов нет: ждём заметное время и считаем вызовы.
    for _ in 0..25 {
        owner.poll_jobs();
        std::thread::sleep(Duration::from_millis(4));
    }
    assert_eq!(downloader.call_count(), 1, "no automatic background retry");

    click_menu_row(&mut owner, "Russian (auto, translated)");
    settle(&mut owner);

    assert_eq!(downloader.call_count(), 2, "the click retried exactly once");
    assert_eq!(owner.lifecycle_view(), SubtitleLifecycleView::Ready);
    assert!(take_failures(&mut owner).is_empty());
    assert!(
        overlay_present(&mut owner, instance(1), 2_000),
        "the retried track draws its cue"
    );
}

#[test]
fn broken_subtitle_file_is_a_permanent_failure_without_a_download_notice() {
    let downloader = FakeWebDownloader::with_replies(vec![srv3_reply("<timedtext><body><p")]);
    let mut owner = web_owner(
        &config_with_languages(false, &[]),
        instance(1),
        web_source(
            vec![web_track(SubtitleKind::Manual, "en", Some("English"))],
            &downloader,
        ),
    );

    click_menu_row(&mut owner, "English");
    settle(&mut owner);

    assert!(matches!(
        owner.unavailable_failure(),
        Some(SubtitleLoadFailure::ParseFailed(_))
    ));
    assert!(
        take_failures(&mut owner).is_empty(),
        "a parse failure is not a download failure"
    );
    let row = owner.menu_view().tracks.remove(0);
    assert!(
        matches!(row.availability, SubtitleTrackAvailability::Unavailable(_)),
        "a track that cannot be parsed is not offered for retry"
    );
}

