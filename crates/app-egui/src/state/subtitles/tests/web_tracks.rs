#[test]
fn debug_output_of_web_tracks_and_failures_never_contains_a_link() {
    let downloader = FakeWebDownloader::with_replies(Vec::new());
    let source = web_source(mixed_tracks(), &downloader);
    let mut texts = vec![format!("{source:?}"), format!("{downloader:?}")];
    for track in mixed_tracks() {
        texts.push(format!("{track:?}"));
    }
    let owner = web_owner(&enabled_config(), instance(1), source);
    texts.push(format!("{:?}", owner.menu_view()));
    for error in [
        WebSubtitleFetchError::UnknownTrack,
        WebSubtitleFetchError::RateLimited {
            retry_after: Some(Duration::from_secs(60)),
        },
        WebSubtitleFetchError::NotFound,
        WebSubtitleFetchError::LinkExpired,
        WebSubtitleFetchError::RefreshFailed,
        WebSubtitleFetchError::NetworkUnavailable,
        WebSubtitleFetchError::Timeout,
        WebSubtitleFetchError::UnexpectedStatus { status: 500 },
        WebSubtitleFetchError::TooLarge { limit_bytes: 10 },
        WebSubtitleFetchError::InvalidResponse,
        WebSubtitleFetchError::Cancelled,
    ] {
        let failure = SubtitleLoadFailure::DownloadFailed(error);
        texts.push(format!("{failure}"));
        texts.push(format!("{failure:?}"));
    }

    for text in texts {
        for forbidden in ["://", "http", "signature", "expire=", "sparams"] {
            assert!(
                !text.to_lowercase().contains(forbidden)
                    || forbidden == "http" && text.contains("HTTP "),
                "`{forbidden}` leaked into `{text}`"
            );
        }
    }
}
