//! Подписи web-дорожек: языки с одним названием (`zh-CN`/`zh-TW`) в меню различимы.

use web_media_core::SubtitleKind;

use super::web_support::*;
use super::*;

fn menu_labels(tracks: Vec<super::super::web_track::WebTrackInfo>) -> Vec<String> {
    let downloader = FakeWebDownloader::with_replies(Vec::new());
    let owner = web_owner(
        &SubtitlesConfig::default(),
        instance(1),
        web_source(tracks, &downloader),
    );
    menu_texts(&owner)
        .into_iter()
        .map(|(text, _)| text)
        .collect()
}

#[test]
fn regional_variants_use_the_source_names_and_single_languages_stay_short() {
    let labels = menu_labels(vec![
        web_track(SubtitleKind::Manual, "zh-CN", Some("Chinese (China)")),
        web_track(SubtitleKind::Manual, "zh-TW", Some("Chinese (Taiwan)")),
        web_track(
            SubtitleKind::Manual,
            "en-US",
            Some("English (United States)"),
        ),
        web_track(SubtitleKind::Manual, "fr", Some("French")),
    ]);

    assert_eq!(
        labels,
        ["Chinese (China)", "Chinese (Taiwan)", "English", "French"]
    );
}

#[test]
fn regional_variants_without_a_useful_source_name_get_the_language_tag() {
    let labels = menu_labels(vec![
        web_track(SubtitleKind::Manual, "pt-BR", None),
        web_track(SubtitleKind::Manual, "pt-PT", Some("Português")),
        web_track(
            SubtitleKind::Manual,
            "zh-Hans",
            Some("Chinese (Simplified)"),
        ),
        web_track(
            SubtitleKind::Manual,
            "zh-Hant",
            Some("Chinese (Traditional)"),
        ),
    ]);

    assert_eq!(
        labels,
        [
            "Chinese (Simplified)",
            "Chinese (Traditional)",
            "Portuguese (pt-BR)",
            "Portuguese (pt-PT)"
        ]
    );
}

#[test]
fn twins_are_compared_within_one_kind_because_the_kind_is_part_of_the_label() {
    // Распознанная речь `es` и автоперевод `es-419` называются по-разному за счёт «(auto)» и
    // «(auto, translated)»: уточнять нечего.
    let labels = menu_labels(vec![
        web_track(SubtitleKind::AutoGenerated, "es", Some("Spanish")),
        web_track(
            SubtitleKind::AutoTranslated,
            "es-419",
            Some("Spanish (Latin America)"),
        ),
    ]);

    assert_eq!(labels, ["Spanish (auto)", "Spanish (auto, translated)"]);
}

#[test]
fn every_label_in_a_large_menu_is_unique() {
    let tags = [
        "zh-CN", "zh-TW", "zh-Hans", "zh-Hant", "pt-BR", "pt-PT", "es", "es-419", "es-US",
    ];
    let labels = menu_labels(
        tags.iter()
            .map(|tag| web_track(SubtitleKind::AutoTranslated, tag, None))
            .collect(),
    );

    let unique: std::collections::BTreeSet<&String> = labels.iter().collect();
    assert_eq!(unique.len(), tags.len(), "labels: {labels:?}");
}
