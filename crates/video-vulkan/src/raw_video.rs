use ash::vk;
use std::ffi::c_void;

// ═══════════════════════════════════════════════════════════════════════════════
// Блок 1: Структура StdVideoDecodeVP9PictureInfo
// ═══════════════════════════════════════════════════════════════════════════════
// Эта структура описывает параметры одного кадра (picture) при декодировании VP9.
// В спецификации Vulkan Video она называется StdVideoDecodeVP9PictureInfo и
// находится в заголовочном файле vk_video/vulkan_video_codec_vp9std_decode.h.
// Мы определяем её вручную, потому что библиотека ash 0.38 не включает
// VP9-специфичные типы — только базовые Video KHR структуры.

/// Структура, описывающая параметры декодирования одного кадра VP9.
/// Соответствует StdVideoDecodeVP9PictureInfo из Vulkan Video.
#[repr(C)]
// Гарантируем C-совместимый layout памяти (важно для FFI с Vulkan)
#[derive(Debug, Copy, Clone, Default)] // Автоматически реализуем:
// Debug — для печати отладочной информации,
// Copy — для копирования по значению,
// Clone — для явного клонирования,
// Default — для создания значения по умолчанию.
pub struct StdVideoDecodeVP9PictureInfo {
    /// Ширина кадра минус 1. Хранится в формате минус-1 для экономии бита
    /// (если ширина не может быть нулевой, то минимальное значение — 0,
    /// что означает ширину 1). Это стандартный трюк в видеокодеках.
    pub frame_width_minus_1: u16,

    /// Высота кадра минус 1. Аналогично frame_width_minus_1.
    pub frame_height_minus_1: u16,

    /// Ширина области отображения (render width) минус 1.
    /// Может отличаться от frame_width, если кадр кодируется с апсемплингом.
    pub render_width_minus_1: u16,

    /// Высота области отображения (render height) минус 1.
    pub render_height_minus_1: u16,

    /// Флаги обновления опорных кадров. Каждый бит указывает,
    /// нужно ли обновить соответствующий слот опорного кадра текущим кадром.
    /// Бит 0 = слот 0, бит 1 = слот 1, и т.д.
    pub refresh_frame_flags: u8,

    /// Тип кадра: 0 — ключевой кадр (keyframe, intra-frame),
    /// 1 — межкадровый (inter frame, предсказываемый).
    pub frame_type: u8,

    /// Зарезервированное поле для выравнивания структуры по памяти.
    /// Не используется, но должно присутствовать для точного соответствия
    /// C-структуре из Vulkan Video.
    pub _reserved1: u8,

    /// Ещё одно зарезервированное поле для выравнивания.
    pub _reserved2: u8,
}

// ═══════════════════════════════════════════════════════════════════════════════
// Блок 2: Перечисление StdVideoVP9Profile
// ═══════════════════════════════════════════════════════════════════════════════
// VP9 определяет 4 профиля, которые различаются поддерживаемыми
// форматами субдискретизации цвета (chroma subsampling) и глубиной цвета.

/// Перечисление профилей VP9. Каждый профиль поддерживает разные
/// комбинации цветовых форматов и битовой глубины.
#[repr(C)]
// C-совместимый layout — enum будет представлен как целое число
#[derive(Debug, Copy, Clone, PartialEq, Eq, Default)] // PartialEq и Eq — для сравнения на равенство
pub enum StdVideoVP9Profile {
    /// Профиль 0: 8-битный, 4:2:0 chroma subsampling.
    /// Самый базовый и широко поддерживаемый профиль.
    #[default]
    Profile0 = 0,

    /// Профиль 1: 8-битный, 4:2:0, 4:2:2 или 4:4:4 chroma subsampling.
    /// Расширяет Profile0 дополнительными форматами субдискретизации.
    Profile1 = 1,

    /// Профиль 2: 10-битный или 12-битный, 4:2:0 chroma subsampling.
    /// Поддерживает повышенную битовую глубину при базовой субдискретизации.
    Profile2 = 2,

    /// Профиль 3: 10-битный или 12-битный, все форматы chroma subsampling.
    /// Максимальный профиль с полной поддержкой битовой глубины и форматов.
    Profile3 = 3,
}

// ═══════════════════════════════════════════════════════════════════════════════
// Блок 3: Структура VideoDecodeVP9PictureInfoKHR
// ═══════════════════════════════════════════════════════════════════════════════
// Это Vulkan-расширение (KHR = Khronos extension), которое передаётся
// в структуру VkVideoDecodeInfoKHR при вызове vkCmdDecodeVideoKHR.
// Оно указывает на StdVideoDecodeVP9PictureInfo и содержит смещения
// в битстриме для разных секций VP9-кадра.

/// Структура расширения KHR для декодирования VP9-кадра.
/// Передаётся через цепочку pNext при вызове vkCmdDecodeVideoKHR.
#[repr(C)] // C-совместимый layout для передачи в Vulkan драйвер
#[derive(Debug, Copy, Clone)] // Автоматические трейты (без Default, т.к. реализуем вручную)
pub struct VideoDecodeVP9PictureInfoKHR {
    /// Тип структуры — должен быть VIDEO_DECODE_VP9_PICTURE_INFO_KHR.
    /// Vulkan использует это поле для идентификации структуры в цепочке pNext.
    pub s_type: vk::StructureType,

    /// Указатель на следующую структуру в цепочке pNext.
    /// std::ptr::null() означает, что в цепочке нет следующей структуры.
    pub p_next: *const c_void,

    /// Указатель на структуру StdVideoDecodeVP9PictureInfo.
    /// Содержит основные параметры кадра (размеры, тип, флаги обновления).
    pub p_std_picture_info: *const StdVideoDecodeVP9PictureInfo,

    /// Смещение в битстриме до начала несжатого заголовка VP9.
    /// Несжатый заголовок содержит синтаксические элементы фрейма.
    pub uncompressed_header_offset: u32,

    /// Смещение в битстриме до начала сжатого заголовка VP9.
    /// Сжатый заголовок содержит данные сжатые энтропийным кодером.
    pub compressed_header_offset: u32,

    /// Смещение в битстриме до начала тайлов (tiles).
    /// VP9 может разбивать кадр на независимо декодируемые тайлы.
    pub tiles_offset: u32,

    /// Индексы слотов опорных кадров для 8 возможных reference_name.
    /// Значение -1 означает, что слот не используется.
    /// Массив из 8 элементов соответствует 8 опорным кадрам VP9.
    pub reference_name_slot_indices: [i8; 8],
}

/// Реализация Default для VideoDecodeVP9PictureInfoKHR.
/// Позволяет создать структуру с безопасными значениями по умолчанию.
impl Default for VideoDecodeVP9PictureInfoKHR {
    fn default() -> Self {
        Self {
            // Устанавливаем корректный тип структуры для Vulkan.
            s_type: VIDEO_DECODE_VP9_PICTURE_INFO_KHR,

            // Цепочка pNext пуста — нет дополнительных расширений.
            p_next: std::ptr::null(),

            // Пока нет указателя на StdVideoDecodeVP9PictureInfo.
            // Вызывающий код должен установить его перед использованием.
            p_std_picture_info: std::ptr::null(),

            // Все смещения по умолчанию равны нулю.
            // Вызывающий код должен установить реальные смещения из битстрима.
            uncompressed_header_offset: 0,
            compressed_header_offset: 0,
            tiles_offset: 0,

            // Все 8 слотов опорных кадров помечены как неиспользуемые (-1).
            // Это безопасное значение: ни один слот не активен по умолчанию.
            reference_name_slot_indices: [-1; 8],
        }
    }
}

// ═══════════════════════════════════════════════════════════════════════════════
// Блок 4: Структура VideoDecodeVP9ProfileInfoKHR
// ═══════════════════════════════════════════════════════════════════════════════
// Эта структура передаётся в цепочке pNext структуры VkVideoProfileInfoKHR
// при создании видео-объектов (VkVideoSession, VkVideoSessionParameters).
// Она сообщает драйверу, какой профиль VP9 будет использоваться.

/// Структура расширения KHR, указывающая профиль VP9 для видео-сессии.
/// Встраивается в цепочку pNext структуры VkVideoProfileInfoKHR.
#[repr(C)] // C-совместимый layout для Vulkan FFI
#[derive(Debug, Copy, Clone, Default)] // Автоматические трейты
pub struct VideoDecodeVP9ProfileInfoKHR {
    /// Тип структуры — VIDEO_DECODE_VP9_PROFILE_INFO_KHR.
    /// Идентифицирует структуру для Vulkan драйвера.
    pub s_type: vk::StructureType,

    /// Указатель на следующую структуру в цепочке pNext.
    /// null означает конец цепочки.
    pub p_next: *const c_void,

    /// Профиль VP9 (Profile0..Profile3).
    /// Определяет поддерживаемые форматы и битовую глубину.
    pub std_profile: StdVideoVP9Profile,
}

// ═══════════════════════════════════════════════════════════════════════════════
// Блок 5: Константы структурных типов и флагов
// ═══════════════════════════════════════════════════════════════════════════════
// Vulkan использует перечисление VkStructureType для идентификации структур.
// Каждое расширение определяет свои уникальные значения.
// Значения для VP9 не включены в ash 0.38, поэтому задаём их вручную
// через from_raw с числовыми значениями из спецификации Vulkan.

/// Константа типа структуры для VideoDecodeVP9PictureInfoKHR.
/// Значение 1000499000 взято из Vulkan спецификации.
/// Используется в поле s_type структуры VideoDecodeVP9PictureInfoKHR.
pub const VIDEO_DECODE_VP9_PICTURE_INFO_KHR: vk::StructureType =
    vk::StructureType::from_raw(1000499000);

/// Константа типа структуры для VideoDecodeVP9ProfileInfoKHR.
/// Значение 1000499001 — следующее после PICTURE_INFO в спецификации.
/// Используется в поле s_type структуры VideoDecodeVP9ProfileInfoKHR.
pub const VIDEO_DECODE_VP9_PROFILE_INFO_KHR: vk::StructureType =
    vk::StructureType::from_raw(1000499001);

/// Флаг кодековой операции декодирования VP9.
/// Vulkan Video использует флаги для указания поддерживаемых операций.
/// Значение 0x00000008 соответствует VP9 decode.
///
/// Примечание: ash 0.38 включает флаги для H264 (0x00000001),
/// H265 (0x00000002) и AV1 (0x00000004), но НЕ включает VP9.
/// Поэтому определяем его вручную.
pub const VIDEO_CODEC_OPERATION_DECODE_VP9_BIT_KHR: vk::VideoCodecOperationFlagsKHR =
    vk::VideoCodecOperationFlagsKHR::from_raw(0x00000008);
