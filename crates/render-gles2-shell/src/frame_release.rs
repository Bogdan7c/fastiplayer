//! Возврат кадра декодеру только после того, как GPU его дочитал (решения владельца 30 и 32).
//!
//! # Правило
//!
//! Кадр декодера (DMA-BUF у HW zero-copy, плоскости в памяти у SW) возвращается декодеру
//! (`release_frame` внутреннего провайдера) **только после fence кадра показа**, в котором GPU
//! последний раз его трогал, и **ровно один раз**. Правило одно для HW и SW: обёртка не
//! различает путь, она видит только «handle кадра».
//!
//! # Почему отдельный поток-ожидатель
//!
//! Рендер по изменению (egui) умеет спать: если картинка не меняется, следующий кадр UI может не
//! наступить минутами. Если бы освобождение происходило «при следующей отрисовке», последний
//! показанный кадр висел бы у рендера, а пул декодера не получал бы слот назад. Поэтому ждёт
//! fence не поток рендера, а собственный поток адаптера (`gles2-frame-release`): он спит на
//! fence и возвращает кадр сразу, как только GPU закончил, независимо от UI и event loop
//! приложения.
//!
//! # Почему достаточно «последнего fence»
//!
//! Поток рендера после каждого кадра показа публикует его fence
//! ([`Gles2FrameReleaseBinding::publish_presented_frame_fence`]). GL выполняет команды одного
//! контекста строго по порядку, поэтому fence последнего кадра показа покрывает всю прежнюю
//! работу GPU, в том числе любое чтение любого более раннего кадра. Запрос на освобождение
//! приходит после drop последнего ключа кадра в плеере, а рендер публикует fence до возврата из
//! `render_frame`; значит, любой уже нарисованный кадр покрыт опубликованным fence. Если fence
//! ещё ни разу не публиковали, кадр не рисовался и его можно вернуть сразу.
//!
//! # Модули
//!
//! - [`binding`] — публичная привязка: публикация fence, потеря контекста, статистика;
//! - [`detach`] — штатная отвязка рендера перед уничтожением контекста (контракт с рендером);
//! - [`drain`] — ожидание, пока запрошенные освобождения дойдут до декодера (`wait_for_gpu_idle`);
//! - [`shared`] — общее состояние и счётчики, `PendingRelease` с гарантией «ровно один раз»;
//! - [`waiter`] — поток-ожидатель и его жизненный цикл;
//! - [`provider`] и [`decoder`] — обёртки провайдера и декодера (все методы форвардятся);
//! - [`fence`] — узкий трейт fence для подмены в тестах.

