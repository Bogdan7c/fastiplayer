//! Отладочный «отвод» провода: сырые сообщения сеанса до разбора и сторожа поколений.
//!
//! Шов для «чёрного ящика» (сессия 09b2): приложение, если захочет, ставит
//! [`SessionWireTap`], и сервер показывает ему каждое сообщение WebSocket
//! подключённого сеанса ровно так, как оно прошло по проводу:
//! - входящие от страницы — текст и двоичные рамки, **до** `decode_message` /
//!   `decode_data_frame` и до сторожа поколений (устаревшее поколение и даже битое
//!   сообщение тоже видны — для разбора чужих сбоев это главное);
//! - исходящие плеера странице — JSON, как он ушёл в сокет.
//!
//! Без отвода (`None`, то есть всегда в продукте) сервер не делает ни одного лишнего
//! вызова и не копирует ни байта: цена нулевая. Отвод не может ни остановить сервер,
//! ни изменить сообщение: методы ничего не возвращают, а ошибки записи реализация
//! обязана обработать сама (сервер о них не узнает).
//!
//! Вызовы одного соединения идут из его потока строго по порядку кадров на проводе
//! (входящие и исходящие вместе), не перекрываясь. Вызовы разных соединений и
//! [`SessionWireTap::connection_closed`] могут идти из разных потоков.
//!
//! Первое сообщение соединения — `attach` — и ответ `attached` в отвод не попадают:
//! отвод видит только уже подключённый сеанс (пропуск в записи не нужен).

use crate::registry::SessionRef;

/// Наблюдатель за проводом подключённого сеанса (только для отладки).
pub trait SessionWireTap: Send + Sync {
    /// Входящее текстовое сообщение страницы, байты как пришли.
    fn page_text(&self, session: &SessionRef, bytes: &[u8]);

    /// Входящая двоичная рамка страницы, байты как пришли.
    fn page_binary(&self, session: &SessionRef, bytes: &[u8]);

    /// Исходящее сообщение плеера странице (JSON, как отправлено в сокет).
    fn player_text(&self, session: &SessionRef, json: &str);

    /// Соединение сеанса закончилось (закрыто или оборвано): повод сбросить буферы.
    /// После обрыва тот же сеанс может вернуться новым соединением.
    fn connection_closed(&self, session: &SessionRef);
}
