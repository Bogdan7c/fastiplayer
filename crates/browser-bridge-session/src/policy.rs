//! Политика времени и лимитов сеанса моста.
//!
//! Все числа, от которых зависит поведение сервера, собраны здесь и не размазаны
//! по логике (правило проекта «конфиг не хардкодим»). Тесты подставляют свою
//! политику с миллисекундными таймаутами; в бою живёт [`BrowserSessionPolicy::default`].

use std::time::Duration;

/// Сроки и лимиты браузерного режима.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct BrowserSessionPolicy {
    /// Сколько ждать `attach` от нового соединения (считая с момента TCP-подключения,
    /// рукопожатие WebSocket входит в срок). Не успел — закрытие кодом 4007.
    pub attach_timeout: Duration,
    /// Сколько отводим на HTTP-рукопожатие WebSocket (входит в `attach_timeout`).
    pub handshake_timeout: Duration,
    /// Сколько живёт выданный сеанс, к которому никто не подключился. Истёк —
    /// сеанс закончился, процесс может выходить.
    pub first_attach_deadline: Duration,
    /// Сколько ждать повторного `open_session` с тем же ключом после обрыва
    /// соединения БЕЗ кадра закрытия от страницы (service worker экстеншена умер
    /// и перезапускается). Истёк — сеанс закончился.
    pub reconnect_grace: Duration,
    /// Сколько процесс живёт после старта, если сеанс так и не открыли
    /// (D-Bus разбудил нас зря или звонивший исчез).
    pub idle_exit_after_start: Duration,
    /// Сколько одновременных соединений без `attach` терпим; остальные
    /// сбрасываются сразу (защита от залипших и чужих подключений к loopback).
    pub max_unattached_connections: usize,
    /// Гранулярность опроса потока соединения: через столько он замечает
    /// просьбу закрыть и исходящие сообщения, пока в сокете тихо.
    pub connection_poll_interval: Duration,
    /// Сколько звонивших помним как «уже сказали hello» (ограниченная память).
    pub max_remembered_callers: usize,
    /// Глубина очереди исходящих сообщений плеер → страница.
    pub outgoing_queue_capacity: usize,
    /// Сколько ждать записи в сокет; зависший получатель не должен вешать поток.
    pub write_timeout: Duration,
    /// Сколько после нашего кадра закрытия ждём ответный кадр, прежде чем
    /// бросить TCP (иначе RST может съесть кадр закрытия у получателя).
    pub close_linger: Duration,
    /// Сколько `shutdown` ждёт завершения потоков; потом отпускает их (не виснет).
    pub shutdown_join_timeout: Duration,
}

impl Default for BrowserSessionPolicy {
    fn default() -> Self {
        Self {
            // Экстеншен подключается и шлёт attach сразу после session_granted;
            // 5 с покрывают медленный loopback под нагрузкой, но не держат мусор.
            attach_timeout: Duration::from_secs(5),
            // Честный клиент завершает рукопожатие за миллисекунды; 2 с освобождают
            // место у залипших и «не-WebSocket» подключений вдвое быстрее attach.
            handshake_timeout: Duration::from_secs(2),
            // Между «выдали пропуск» и attach проходит миллисекунды; 15 с — запас
            // на холодный старт service worker и повторные попытки.
            first_attach_deadline: Duration::from_secs(15),
            // Перезапуск service worker и новый open_session занимают единицы секунд;
            // 10 с не дают процессу висеть, если человек закрыл браузер.
            reconnect_grace: Duration::from_secs(10),
            // D-Bus-активация без open_session — аварийный случай; 30 с хватает
            // на медленный старт и повтор звонка, дольше жить без дела незачем.
            idle_exit_after_start: Duration::from_secs(30),
            // Честному экстеншену нужно одно соединение, максимум два при повторе;
            // 4 оставляют запас и всё ещё ограничивают чужое.
            max_unattached_connections: 4,
            // 50 пробуждений в секунду на соединение: реакция на закрытие быстрее
            // кадра интерфейса, нагрузка на CPU незаметна.
            connection_poll_interval: Duration::from_millis(20),
            // Звонящих (отдельных процессов-посредников) за жизнь процесса единицы;
            // 32 с запасом, но память не растёт без границы.
            max_remembered_callers: 32,
            // Команды плеера (часы 4/с, play/pause) мелкие; 64 — ~15 с часов, а при
            // полной очереди честнее отказать, чем копить.
            outgoing_queue_capacity: 64,
            // Loopback пишет мгновенно; 5 с — признак мёртвого получателя.
            write_timeout: Duration::from_secs(5),
            // Браузер отвечает на закрытие за миллисекунды; секунда — потолок.
            close_linger: Duration::from_secs(1),
            // Потоки замечают просьбу за один опрос; 2 с — запас на закрытие с linger.
            shutdown_join_timeout: Duration::from_secs(2),
        }
    }
}
