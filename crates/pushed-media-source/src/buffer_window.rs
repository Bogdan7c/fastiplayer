//! Окно буфера и его состояние для того, кто приносит байты (обратное давление).
//!
//! [`BufferWindow::ahead`] — запас вперёд от позиции плеера, после которого
//! источник говорит странице «полон» ([`BufferStatus`]): так честный плеер
//! страницы перестаёт качать, а память источника не растёт.
//!
//! Прошлое полка держит, пока его держит страница (решение владельца 31.10.2026:
//! страница не пришлёт повторно то, что лежит в её собственном буфере, и
//! перемотка туда должна садиться с полки). Уходит оно, когда страница сама его
//! стёрла, или под предохранителем памяти у порога «полон» — и тогда
//! [`BufferWindow::behind`] прошлого у позиции остаётся всё равно.
//!
//! Значения окна — пользовательская настройка (`[browser_session] buffer_ahead_s`,
//! `buffer_behind_s` в config.toml). Этот crate о конфиге не знает: приложение
//! переводит настройку в [`crate::PushedSourcePolicy::with_buffer_window`].

use std::time::Duration;

/// Окно буфера: сколько держать вперёд и назад от позиции плеера.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct BufferWindow {
    /// Запас вперёд, после которого источник говорит «полон». Больше нуля.
    pub ahead: Duration,
    /// Сколько уже показанного прошлого у позиции держать ДАЖЕ при нехватке
    /// памяти: гарантированный минимум для перемотки назад без страницы, а не
    /// окно выселения (в обычной работе полка держит прошлое, пока его держит
    /// страница). Ноль допустим: под предохранителем памяти показанное может
    /// уйти сразу.
    pub behind: Duration,
}

/// Принимает ли источник новые байты без перебора окна.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BufferIntake {
    /// Запас вперёд меньше окна: страница может слать дальше.
    Accepting,
    /// Запас вперёд достиг окна ИЛИ удерживаемые байты достигли доли жёсткого
    /// потолка памяти (у потока с большим битрейтом окно в секундах больше
    /// потолка): странице стоит подождать. Источник байты всё равно примет, пока
    /// не упрётся в жёсткий потолок; между «полон» и потолком — запас на
    /// сегмент, который страница уже несла.
    Full,
}

/// Состояние буфера потока для страницы.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct BufferStatus {
    /// Непрерывный запас вперёд от позиции плеера: по каждой полосе с метками
    /// времени — конец непрерывного куска полки, покрывающего позицию, минус
    /// позиция (ноль, если позиция не покрыта); по потоку — минимум по полосам.
    pub buffered_ahead: Duration,
    /// Принимать ли дальше.
    pub intake: BufferIntake,
}

impl BufferStatus {
    /// Ничего не буферизовано и место есть.
    #[cfg(test)]
    pub(crate) const EMPTY: Self = Self {
        buffered_ahead: Duration::ZERO,
        intake: BufferIntake::Accepting,
    };
}
