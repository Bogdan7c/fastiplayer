//! Стирание страницей: внешняя сторона сама выбросила кусок времени полосы
//! (у браузера — `SourceBuffer.remove(start, end)`).
//!
//! Правило полки «помним, пока помнит страница» (решение владельца 31.10.2026):
//! всё, что страница считает скачанным, есть и у источника — она не пришлёт
//! повторно то, что у неё самой лежит, и перемотка туда должна садиться с полки.
//! Поэтому прошлое уходит с полки, когда страница сама стёрла его у себя (этот
//! модуль), или под предохранителем памяти (`stream_buffer::eviction`).
//!
//! Crate нейтрален к протоколу: здесь свой диапазон, а перевод сообщения моста
//! делает приложение. Время — шкала показа полосы ПОСЛЕ её `timestampOffset`
//! (та же, на которой лежит полка и идёт позиция плеера): MSE `remove()`
//! принимает именно время показа.

use std::time::Duration;

/// Где кончается стёртый диапазон.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PageRemovedRangeEnd {
    /// В этой точке (не включая её).
    At(Duration),
    /// До конца шкалы (`remove(start, Infinity)`).
    EndOfTimeline,
}

/// Диапазон времени, который страница стёрла у себя: `[start, end)`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PageRemovedRange {
    /// Начало (включительно), время показа после смещения полосы.
    start: Duration,
    /// Конец.
    end: PageRemovedRangeEnd,
}

impl PageRemovedRange {
    /// Диапазон `[start, end)`. Пустой или перевёрнутый диапазон допустим и
    /// ничего не отпускает (MSE такой `remove()` отвергает сам, но страница — враг).
    #[must_use]
    pub const fn new(start: Duration, end: PageRemovedRangeEnd) -> Self {
        Self { start, end }
    }

    /// Начало.
    #[must_use]
    pub const fn start(&self) -> Duration {
        self.start
    }

    /// Конец.
    #[must_use]
    pub const fn end(&self) -> PageRemovedRangeEnd {
        self.end
    }
}

/// Что сделала полка полосы со стиранием страницы.
///
/// Отпускаются только сегменты, ЦЕЛИКОМ лежащие в стёртом диапазоне и уже
/// сыгранные; остальные остаются (держать больше, чем страница, безопасно —
/// меньше нельзя). Счётчики «оставлено» — для журнала и тестов.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct PageRemovalReport {
    /// Сколько сегментов отпущено.
    pub released_segments: usize,
    /// Сколько байтов этих сегментов отпущено (на столько уменьшился учёт потока).
    pub released_bytes: usize,
    /// Целиком в диапазоне, но ещё не сыграны (впереди позиции или курсора
    /// подачи): нужны плееру, страница пришлёт замену новым `appendBuffer`.
    pub kept_not_played: usize,
    /// Целиком в диапазоне и сыграны, но их байты ещё в трубе эпизода (демуксер
    /// не дочитал): снимать их сейчас нельзя.
    pub kept_in_pipe: usize,
    /// Задеты диапазоном лишь частично: часть их времени у страницы осталась.
    pub kept_partially_removed: usize,
}

/// Итог стирания страницей для одной полосы.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PageRemovalOutcome {
    /// Полоса с временем: полка разобрала стирание (подробности в отчёте).
    Applied(PageRemovalReport),
    /// Полоса без меток времени (MPEG-TS): полки у неё нет, стирать нечего.
    UntimedLane,
}
