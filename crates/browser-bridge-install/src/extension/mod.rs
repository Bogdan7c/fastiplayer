//! Установщик экстеншена Fastiplayer Bridge (сессия 07a): плеер сам ставит экстеншен
//! в браузеры пользователя там, где браузер это позволяет, и никогда не просит пароль
//! администратора (системные папки не трогаются).
//!
//! # Два пути доставки (решение владельца)
//!
//! 1. «Тихий» — Chromium, Brave, Vivaldi, Edge (пакеты и Flatpak): плеер кладёт в
//!    пользовательскую папку `<профили браузера>/External Extensions/<ID>.json`
//!    подсказку со ссылкой на Chrome Web Store, и браузер сам ставит экстеншен при
//!    следующем запуске ([`hint`]).
//! 2. «Один клик» — фирменный Google Chrome (пакет и Flatpak игнорирует папку) и
//!    семейство Firefox: плеер открывает страницу магазина В ЭТОМ браузере
//!    ([`launch`]), «Add» жмёт человек.
//!
//! # Статус только из чтения
//!
//! Установлен ли экстеншен, узнаём по файлам профилей, которые ведёт сам браузер
//! ([`presence`]); в них мы никогда не пишем. Единственный файл, которым владеем, —
//! наша подсказка; Cancel удаляет только её и лишь отменяет ещё не случившуюся
//! установку: уже поставленный экстеншен убирает человек на странице расширений
//! браузера (Chromium не удаляет его при исчезновении подсказки, проверено вживую).
//!
//! # Карта модулей
//!
//! - [`listing`] — страницы магазинов как значение времени выполнения;
//! - [`hint`] — файл-подсказка: запись, проверка, удаление только своего (чужое и «не обычные файлы» не трогаются);
//! - [`presence`] — чтение профилей Chromium и Firefox;
//! - [`launch`] — шов «открыть адрес в конкретном браузере»;
//! - [`state`] — состояние в каждом браузере и действие кнопки Install;
//! - [`installer`] — фасад [`ExtensionInstaller`](installer::ExtensionInstaller); [`error`] — его ошибки.

