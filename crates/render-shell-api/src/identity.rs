//! Идентичность экземпляра рендера.
//!
//! Билет на буфер swapchain и ключ видеокадра несут «паспорт» рендера, который их выдал.
//! Рендер рисует только по своим билетам и ключам. Так ловится ошибка вызывающего кода
//! (например, ключ старого рендера после пересоздания), а не выдаётся мусор на экран.

use std::sync::atomic::{AtomicU64, Ordering};

/// Счётчик паспортов на весь процесс; 0 не выдаётся никому (зарезервирован под «никто»).
static NEXT_RENDERER_INSTANCE_ID: AtomicU64 = AtomicU64::new(1);

/// Уникальный в пределах процесса номер экземпляра рендера.
///
/// Два созданных подряд рендера одного семейства получают разные номера, поэтому
/// пересоздание рендера делает старые билеты и ключи «чужими».
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct RendererInstanceId(u64);

impl RendererInstanceId {
    /// Выдаёт новый номер. Вызывает конкретный рендер один раз при создании.
    #[must_use]
    pub fn allocate() -> Self {
        // Relaxed достаточно: нужна только уникальность значения, а не порядок с другой памятью.
        Self(NEXT_RENDERER_INSTANCE_ID.fetch_add(1, Ordering::Relaxed))
    }

    /// Номер, который не принадлежит ни одному рендеру (для заведомо чужих билетов в тестах).
    #[cfg(any(test, feature = "conformance"))]
    pub(crate) const fn unowned() -> Self {
        Self(0)
    }

    /// Числовое значение для логов.
    #[must_use]
    pub const fn value(self) -> u64 {
        self.0
    }
}
