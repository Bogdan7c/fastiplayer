#[test]
fn styles_beyond_limit_are_skipped_and_counted() {
    let limits = limits();
    let mut builder = ScriptBuilder::new(&limits, LineScope::HeaderOnly);
    builder.feed_line("[V4+ Styles]");
    for index in 0..6 {
        builder.feed_line(&format!("Style: S{index}"));
    }
    assert_eq!(builder.skipped_styles(), 2);
    let script = builder.finish();
    assert_eq!(script.style_count(), 5);
    assert!(script.lookup_style_strict("S3").is_some());
    assert!(script.lookup_style_strict("S4").is_none());
}

#[test]
fn missing_event_format_falls_back_by_script_kind() {
    let ass = build(&["[V4+ Styles]"]);
    assert_eq!(
        ass.event_format().fields().first(),
        Some(&AssEventField::Layer)
    );
    let ssa = build(&["[V4 Styles]"]);
    assert_eq!(
        ssa.event_format().fields().first(),
        Some(&AssEventField::Ignored)
    );
}

#[test]
fn dialogue_is_ignored_in_header_only_scope_and_parsed_in_full_scope() {
    let limits = limits();
    let line = "Dialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,Hi";
    let mut header = ScriptBuilder::new(&limits, LineScope::HeaderOnly);
    header.feed_line("[Events]");
    assert_eq!(header.feed_line(line), LineOutcome::Handled);
    let mut full = ScriptBuilder::new(&limits, LineScope::FullFile);
    full.feed_line("[Events]");
    match full.feed_line(line) {
        LineOutcome::Dialogue(fields) => assert_eq!(fields.text, "Hi"),
        other => panic!("expected dialogue, got {other:?}"),
    }
    assert_eq!(
        full.feed_line("Dialogue: 0,broken"),
        LineOutcome::BrokenDialogue
    );
    assert_eq!(
        full.feed_line("Comment: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,x"),
        LineOutcome::Handled
    );
}

#[test]
fn lines_outside_known_sections_are_ignored() {
    let script = build(&[
        "PlayResX: 1000",
        "[Fonts]",
        "PlayResX: 2000",
        "[Script Info]",
    ]);
    assert_eq!(script.info().play_res.width, 384);
}
